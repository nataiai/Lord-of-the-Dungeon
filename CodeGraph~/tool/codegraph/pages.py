"""Markdown pages (GitHub draws the Mermaid blocks): the index and one short page per .cs file.

Kept short on purpose: one line of description, a small map, one chart per function. The exact code is one click
away (collapsed tables), never in the way.
"""
from __future__ import annotations

import posixpath
from urllib.parse import quote

from .mermaid import (PHASE_ORDER, UNITY_PHASE, UNITY_WHEN, MapBuilder, esc, flow_to_mermaid, mid_node, node_text,
                      short)
from .model import Model
from .notes import badge

GENERATED = ("<!-- Generated by CodeGraph (CodeGraph~/tool). Don't edit: run the generator. "
             "Notes live in CodeGraph~/notes/. -->")
PER_FRAME_EVENTS = {"Update", "LateUpdate", "FixedUpdate", "OnTriggerStay2D", "OnCollisionStay2D", "OnTriggerStay",
                    "OnCollisionStay", "OnGUI"}
LEGEND = "⚡ Unity calls it · 🔁 runs every frame · ⏳ can wait · blue box = calls another function · gray box = simple math"
CALLS = ("call", "base")

ROOT = "../.."  # the repo root, relative to the output folder (cli.py sets it)


def page_path(src: str) -> str:
    return src + ".md"


def rel(from_page: str, to: str) -> str:
    """Relative link target, URL-encoded (folder names like `Data Types` have spaces)."""
    return quote(posixpath.relpath(to, posixpath.dirname(from_page) or "."), safe="/~.-_")


def per_frame(model: Model) -> set:
    """Functions reachable from a per-frame Unity event: changing them costs performance."""
    todo = [mid for mid, mi in model.members.items() if mi.unity_event and mi.member.name in PER_FRAME_EVENTS]
    seen = set(todo)
    while todo:
        mid = todo.pop()
        mi = model.members.get(mid)
        if mi is None:
            continue
        for k, t in mi.uses:
            if k in CALLS and t not in seen and t in model.members:
                seen.add(t)
                todo.append(t)
    return seen


def icon(mi, frame: set) -> str:
    s = "⚡" if mi.unity_event else ("⏳" if mi.coroutine else "")
    if mi.id in frame and not mi.unity_event:
        s += "🔁"
    return s + (" " if s else "")


def esc_md(s: str) -> str:
    return s.replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")


def _anchor(mid: str) -> str:
    return "m-" + "".join(ch if ch.isalnum() else "-" for ch in mid).strip("-").lower()


def display_name(model: Model, here_type: str):
    """Callee names as a reader wants them: `Died` in the same class, `PathFinding.Direction` elsewhere."""
    def name(mid: str) -> str:
        tm = model.project.member_by_id.get(mid)
        n = short(mid).split("(")[0].replace(" · ", ".")
        if tm is not None and tm.owner != here_type:
            owner = tm.owner.split(".")[-1]
            return f"{owner}.{n}"
        return n
    return name


def apply_labels(model: Model, mi, note) -> None:
    """Put the AI's short labels on the boxes (by box id) and a short title on the start box."""
    steps = note.steps if note is not None else {}
    for n in mi.flow.nodes:
        n.label = steps.get(n.id, "") if n.kind not in ("start", "end", "join") else ""
    start = mi.flow.nodes[0]
    start.label = icon(mi, set()) + (mi.member.name.replace(".", " · ") if mi.member.kind == "accessor" else mi.member.name)


def is_chart(mi) -> bool:
    return len(mi.flow.steps) >= 2


def _member_link(model: Model, page: str, target: str, label: str) -> str:
    tm = model.project.member_by_id.get(target)
    t = model.project.types.get(tm.owner) if tm is not None else None
    if t is None or model.project.path_is_external(t.file):
        return f"`{label}`"
    target_page = page_path(t.file)
    here = rel(page, target_page) if target_page != page else ""
    return f"[`{label}`]({here}#{_anchor(target)})"


# ----------------------------------------------------------------------------- file map

def map_members(model: Model, path: str) -> list:
    """The middle of a file map: its functions (and property code that calls something complex)."""
    out = []
    for mi in sorted(model.file_members(path), key=lambda m: m.member.line):
        calls_complex = any(k in CALLS and t in model.complex for k, t in mi.uses)
        if mi.member.kind == "accessor" and not calls_complex:
            continue
        out.append(mi)
    return out


def file_map(model: Model, path: str, frame: set, status: dict | None = None, only_type: str | None = None) -> str:
    """Who calls in (Unity first) -> this file's functions -> the complex functions they call.

    Calls to simple-math helpers are left out: they're inside the gray boxes of the charts.
    """
    status = status or {}
    p = model.project
    mb = MapBuilder("LR", diff=bool(status))
    mine = [mi for mi in map_members(model, path) if only_type is None or mi.type.full == only_type]
    ids = {mi.id for mi in mine}
    own_types = {only_type} if only_type else {t.full for t in model.files[path].types}
    multi = len({mi.type.full for mi in mine}) > 1
    for mi in mine:
        label = icon(mi, frame) + (mi.type.name + "." if multi else "") + short(mi.id).split("(")[0]
        calls_complex = any(k in CALLS and t in model.complex for k, t in mi.uses)
        mb.node(mid_node(mi.id), esc(label), "ownev" if mi.unity_event else "own",
                shape="sub" if calls_complex else "rect", status=status.get(mi.id, "same"))
    for mi in mine:
        if mi.unity_event:
            ph = UNITY_PHASE.get(mi.member.name, "callback")
            u = mb.node("U_" + ph.replace(" ", "_").replace("-", "_"), f"Unity · {ph}", "engine", shape="stadium")
            mb.edge(u, mid_node(mi.id), "", "engine")
    calling: dict[str, list] = {}
    used: dict[str, list] = {}
    edges = []
    for mi in mine:
        for c in model.callers.get(mi.id, []):
            cm = model.members.get(c)
            if cm is None or cm.type.full in own_types:
                continue
            calling.setdefault(cm.type.full, [])
            nm = short(c).split("(")[0]
            if nm not in calling[cm.type.full]:
                calling[cm.type.full].append(nm)
            edges.append(("in:" + cm.type.full, mi.id))
    for mi in mine:
        for k, target in mi.uses:
            if k not in CALLS or target not in model.complex:
                continue
            tm = p.member_by_id.get(target)
            if tm is None:
                continue
            if tm.owner in own_types:
                if target in ids and target != mi.id:
                    edges.append((mi.id, target))
                continue
            used.setdefault(tm.owner, [])
            nm = short(target).split("(")[0]
            if nm not in used[tm.owner]:
                used[tm.owner].append(nm)
            edges.append((mi.id, "out:" + tm.owner))

    def type_node(side: str, full: str, members: list):
        ext = p.is_external_type(full)
        shown = members[:4] + ([f"+{len(members) - 4}"] if len(members) > 4 else [])
        label = f"<b>{esc(full.split('.')[-1])}</b>" + ("<br><i>AI/ external</i>" if ext else "") + "<br>" + esc(", ".join(shown))
        mb.node(mid_node(side + "_" + full), label, "ext" if ext else "other", status=status.get(side + ":" + full, "same"))

    linked = {a for a, b in edges} | {b for a, b in edges} | {mi.id for mi in mine if mi.unity_event}
    for mi in mine:
        if mi.id not in linked:
            mb.nodes.pop(mid_node(mi.id), None)
    for full, ms in sorted(calling.items()):
        type_node("in", full, ms)
    for full, ms in sorted(used.items()):
        type_node("out", full, ms)
    for a, b in edges:
        na = mid_node(a.replace(":", "_", 1)) if a.startswith("in:") else mid_node(a)
        nb = mid_node(b.replace(":", "_", 1)) if b.startswith("out:") else mid_node(b)
        mb.edge(na, nb, "", "call", status.get(("edge", a, b), "same"))
    return mb.render()


# ----------------------------------------------------------------------------- file page

def _src(page: str, path: str, a: int, b: int) -> str:
    target = rel(page, ROOT + "/" + path)
    return f"[L{a}–{b}]({target}#L{a}-L{b})" if a != b else f"[L{a}]({target}#L{a})"


def _note_line(note) -> str:
    """One short line: the AI's description, marked as AI-written (and flagged if the code changed since)."""
    if note is None or not note.text:
        return ""
    return f"{badge(note)} {note.text.splitlines()[0].strip()}"


def code_table(model: Model, page: str, path: str, mi) -> list:
    name = display_name(model, mi.type.full)
    rows = ["| Step | Code |", "|---|---|"]
    for n in mi.flow.steps:
        if n.kind == "case":
            continue
        step = esc_md(node_text(n, name))
        links = [_member_link(model, page, c, name(c)) for c in dict.fromkeys(n.calls)]
        if links:
            step += " → " + ", ".join(links)
        code = "<br>".join(f"<code>{esc_md(l.text)}</code> <sub>L{l.line}</sub>" for l in n.lines)
        rows.append(f"| {step} | {code} |")
    return rows


def file_page(model: Model, path: str, page: str, notes: list, frame: set, notes_dir_rel: str) -> str:
    fi = model.files[path]
    by_target = {n.target: n for n in notes}
    mine = sorted(model.file_members(path), key=lambda mi: mi.member.line)
    L = [GENERATED, f"# {path}", ""]
    for t in fi.types:
        line = _note_line(by_target.get(t.full))
        if line:
            L += [line + ("" if len(fi.types) == 1 else f" *({t.name})*"), ""]
    L += [f"<sub>{LEGEND} · [code]({rel(page, ROOT + '/' + path)}) · [all files]({rel(page, 'index.md')})</sub>", ""]
    if fi.external:
        L += ["*External folder: shown only through what other files use.*", ""]
    # map: one per class when a file has several
    map_types = []
    for mi in map_members(model, path):
        if mi.type.full not in map_types:
            map_types.append(mi.type.full)
    for tfull in map_types:
        split = len(map_types) > 1
        L += [f"## Map{' · ' + tfull if split else ''}", "", "```mermaid",
              file_map(model, path, frame, only_type=tfull if split else None), "```", ""]
    charts = [mi for mi in mine if is_chart(mi)]
    small = [mi for mi in mine if not is_chart(mi)]
    for mi in charts:
        note = by_target.get(mi.id)
        apply_labels(model, mi, note)
        when = (" · " + UNITY_WHEN[mi.member.name]) if mi.unity_event and mi.member.name in UNITY_WHEN else ""
        title = mi.member.name.replace(".", " · ") if mi.member.kind == "accessor" else mi.member.name
        L += [f'<a id="{_anchor(mi.id)}"></a>', "", f"## {icon(mi, frame)}{esc_md(title)}{when}", ""]
        line = _note_line(note)
        if line:
            L += [line, ""]
        if note is not None and note.image and note.image.get("path"):
            img = quote(f"{notes_dir_rel}/{note.image['path']}", safe="/~.-_")
            L += [f"![{note.image.get('alt', '')}]({img})", ""]
        L += ["```mermaid", flow_to_mermaid(mi.flow, unity_event=mi.member.name if mi.unity_event else None,
                                            coroutine=mi.coroutine, short_name=display_name(model, mi.type.full)),
              "```", ""]
        L += [f"<details><summary>Code (L{mi.member.line}–{mi.member.end})</summary>", ""]
        L += code_table(model, page, path, mi)
        L += ["", "Source: " + _src(page, path, mi.member.line, mi.member.end)]
        L += ["", "</details>", ""]
    if small:
        L += [f"<details><summary>Small helpers ({len(small)})</summary>", "", "| | Name | Does | Code |", "|---|---|---|---|"]
        for mi in small:
            note = by_target.get(mi.id)
            apply_labels(model, mi, note)
            steps = mi.flow.steps
            if note is not None and note.text:
                does = note.text.splitlines()[0]
            elif mi.member.kind == "accessor":
                does = ""  # a one-line getter / setter: its code says it all
            else:
                does = node_text(steps[0], display_name(model, mi.type.full)) if steps else "nothing"
            code = "<br>".join(f"<code>{esc_md(l.text)}</code>" for n in steps for l in n.lines) or "*(empty)*"
            title = mi.member.name.replace(".", " · ") if mi.member.kind == "accessor" else mi.member.name
            L.append(f'| {icon(mi, frame).strip()} | <a id="{_anchor(mi.id)}"></a>{esc_md(title)} | {esc_md(does)} | '
                     f"{code} {_src(page, path, mi.member.line, mi.member.end)} |")
        L += ["", "</details>", ""]
    for t in fi.types:
        fields = [m for m in t.members if m.kind in ("field", "const", "event", "property", "enum_member")]
        if not fields:
            continue
        L += [f"<details><summary>{'Values' if t.kind == 'enum' else 'Fields'} · {t.name} ({len(fields)})</summary>",
              "", "| Name | Type | Default | Note |", "|---|---|---|---|"]
        for m in fields:
            val = m.init
            if m.kind == "property":
                g = m.accessors.get("get")
                if g is not None and g.stmts and len(g.stmts) == 1 and g.stmts[0].kind == "simple" and not m.accessors.get("set"):
                    val = "=> " + g.stmts[0].text
            shown = ("`" + esc_md(val) + "`") if val else ""
            insp = " *(Inspector)*" if m.kind == "field" and ("public" in m.mods or "SerializeField" in m.attrs) \
                and not m.is_static and "PlayModeOnly" not in m.attrs and "HideInInspector" not in m.attrs else ""
            L.append(f"| `{m.name}`{insp} | `{esc_md(m.type)}` | {shown} | {esc_md(m.tooltip or m.comment)} |")
        L += ["", "</details>", ""]
    orphans = [n for n in notes if n.status == "orphaned"]
    if orphans:
        L += ["**Notes whose code is gone:** " + ", ".join(f"`{n.target}`" for n in orphans), ""]
    return "\n".join(L) + "\n"


# ----------------------------------------------------------------------------- index

def folder_of(path: str) -> str:
    d = posixpath.dirname(path)
    return d or "(root)"


def folder_map(model: Model) -> str:
    mb = MapBuilder("LR")
    p = model.project
    sizes: dict[str, list] = {}
    for f in model.files.values():
        sizes.setdefault(folder_of(f.path), [0, 0])
        sizes[folder_of(f.path)][0] += 1
        sizes[folder_of(f.path)][1] += f.lines
    for d, (nf, nl) in sorted(sizes.items()):
        ext = any(p.path_is_external(f) for f in model.files if folder_of(f) == d)
        mb.node(mid_node("F_" + d), f"<b>{esc(d)}</b><br>{nf} files", "ext" if ext else "own")
    counts: dict[tuple, int] = {}
    for (a, b), kinds in model.type_deps.items():
        if not kinds & {"calls", "writes", "creates", "inherits"}:
            continue
        fa, fb = folder_of(p.types[a].file), folder_of(p.types[b].file)
        if fa != fb:
            counts[(fa, fb)] = counts.get((fa, fb), 0) + 1
    for (fa, fb), n in sorted(counts.items()):
        mb.edge(mid_node("F_" + fa), mid_node("F_" + fb), f"{n}", "call")
    return mb.render()


def lifecycle_table(model: Model, page: str, pages_written: set) -> list:
    rows: dict[str, dict] = {}
    for mid, mi in sorted(model.members.items()):
        if mi.unity_event and not model.project.is_external_type(mi.type.full):
            ph = UNITY_PHASE.get(mi.member.name, "callback")
            rows.setdefault(mi.type.full, {}).setdefault(ph, []).append(mi)
    phases = [ph for ph in PHASE_ORDER if any(ph in r for r in rows.values())]
    out = ["| Class | " + " | ".join(phases) + " |", "|---|" + "---|" * len(phases)]
    for full in sorted(rows):
        t = model.project.types[full]
        cells = []
        for ph in phases:
            names = []
            for mi in rows[full].get(ph, []):
                if t.file in pages_written:
                    names.append(f"[{mi.member.name}]({rel(page, page_path(t.file))}#{_anchor(mi.id)})")
                else:
                    names.append(mi.member.name)
            cells.append(", ".join(names))
        out.append(f"| `{full}` | " + " | ".join(cells) + " |")
    return out


def index_page(model: Model, page: str, notes_by_file: dict, frame: set, pages_written: set, coverage: tuple) -> str:
    files = sorted(model.files.values(), key=lambda f: (f.external, f.path))  # your code first, AI/ last
    L = [GENERATED, "# Lord of the Dungeon · code as pictures", ""]
    L += [f"{len(files)} files. Each page shows one file: who calls it, and one small chart per function. "
          f"`AI/` is treated as an outside library.", ""]
    L += ["## Folders", "", "Arrow number: how many classes in one folder use the other.", "", "```mermaid",
          folder_map(model), "```", ""]
    L += ["## Files", "", "| File | What it is | Functions |", "|---|---|---|"]
    for f in files:
        notes = {n.target: n for n in notes_by_file.get(f.path, [])}
        what = ""
        for t in f.types:
            n = notes.get(t.full)
            if n is not None and n.text:
                what = n.text.splitlines()[0]
                break
        mems = [mi for mi in model.file_members(f.path) if mi.member.kind != "accessor"]
        name = f"[{f.path}]({rel(page, page_path(f.path))})" if f.path in pages_written else f.path
        if f.external:
            name += " *(external)*"
        L.append(f"| {name} | {esc_md(what)} | {len(mems)} |")
    L += ["", "<details><summary>What Unity runs, and when</summary>", ""]
    L += lifecycle_table(model, page, pages_written)
    L += ["", "</details>", ""]
    return "\n".join(L) + "\n"
