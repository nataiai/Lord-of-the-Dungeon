GENERATED = ("<!-- Generated by CodeGraph (CodeGraph~/tool). Do not edit this file: run the generator. "
             "AI / human notes live in CodeGraph~/notes/. -->")
PER_FRAME_EVENTS = {"Update", "LateUpdate", "FixedUpdate", "OnTriggerStay2D", "OnCollisionStay2D", "OnTriggerStay",
                    "OnCollisionStay", "OnGUI"}
LEGEND = ("⚡ Unity calls it · ⏳ coroutine · 🔁 runs every frame (reached from Update / FixedUpdate / …) · "
          "double-edged box = calls project code · dashed = `AI/` (external) · *L12* = source line")


ROOT = "../.."  # the repo root, relative to the output folder (cli.py sets it)


def page_path(src: str) -> str:
    return src + ".md"


def rel(from_page: str, to: str) -> str:
    return posixpath.relpath(to, posixpath.dirname(from_page) or ".")


def per_frame(model: Model) -> set:
    """Members reachable through calls from a per-frame Unity event (Rider-style 'performance critical' context)."""
    todo = [mid for mid, mi in model.members.items() if mi.unity_event and mi.member.name in PER_FRAME_EVENTS]
    seen = set(todo)
    while todo:
        mid = todo.pop()
        mi = model.members.get(mid)
        if mi is None:
            continue
        for k, t in mi.uses:
            if k in ("call", "base") and t not in seen and t in model.members:
                seen.add(t)
                todo.append(t)
    return seen


def icon(mi, frame: set) -> str:
    s = "⚡" if mi.unity_event else ("⏳" if mi.coroutine else "")
    if mi.id in frame and not mi.unity_event:
        s += "🔁"
    return s + (" " if s else "")


def _type_title(model: Model, t) -> str:
    bases = ", ".join(t.bases)
    ext = model.project.is_external_type(t.full)
    return f"{t.kind} {t.name}" + (f" : {bases}" if bases else "") + ("  (external)" if ext else "")


# ----------------------------------------------------------------------------- file map (butterfly)

CALLS = ("call", "base")


def map_members(model: Model, path: str) -> list:
    """What a file map shows in the middle: methods / constructors, and property accessors that run project code."""
    out = []
    for mi in sorted(model.file_members(path), key=lambda m: m.member.line):
        if mi.member.kind == "accessor" and not any(k in CALLS for k, _ in mi.uses):
            continue
        out.append(mi)
    return out


def file_map(model: Model, path: str, frame: set, status: dict | None = None, only_type: str | None = None) -> str:
    """Butterfly map: who calls in (Unity first) -> this file's methods -> the classes they use.

    Other classes are aggregated into one node each, listing the members used (research: aggregate, don't drop,
    and keep a view near 20 nodes). Precise per-method calls are listed under each flowchart.
    status (diff mode): {node key: added|removed|modified|impacted}.
    """
    status = status or {}
    p = model.project
    mb = MapBuilder("LR", diff=bool(status))
    mine = [mi for mi in map_members(model, path) if only_type is None or mi.type.full == only_type]
    ids = {mi.id for mi in mine}
    own_types = {only_type} if only_type else {t.full for t in model.files[path].types}
    multi = len({mi.type.full for mi in mine}) > 1
    for mi in mine:
        label = icon(mi, frame) + (mi.type.name + " · " if multi else "") + short(mi.id)
        mb.node(mid_node(mi.id), esc(label), "ownev" if mi.unity_event else "own",
                shape="sub" if any(k in CALLS for k, _ in mi.uses) else "rect", status=status.get(mi.id, "same"))
    # Unity engine phases call the event methods
    for mi in mine:
        if mi.unity_event:
            ph = UNITY_PHASE.get(mi.member.name, "callback")
            u = mb.node("U_" + ph.replace(" ", "_").replace("-", "_"), f"Unity · {ph}", "engine", shape="stadium")
            mb.edge(u, mid_node(mi.id), "", "engine")
    # aggregated neighbour classes
    used: dict[str, list] = {}  # type -> members used (callee side)
    calling: dict[str, list] = {}  # type -> members that call in (caller side)
    edges = []
    for mi in mine:
        for c in model.callers.get(mi.id, []):
            cm = model.members.get(c)
            if cm is None or cm.type.full in own_types:
                continue
            calling.setdefault(cm.type.full, [])
            if short(c) not in calling[cm.type.full]:
                calling[cm.type.full].append(short(c))
            direct = any(t == mi.id for k, t in cm.uses)
            edges.append(("in:" + cm.type.full, mi.id, "" if direct else "virtual", "call"))
    for mi in mine:
        chain = {t.full for t in p.base_chain(mi.type)}
        for k, target in mi.uses:
            tm = p.member_by_id.get(target)
            if tm is None:
                continue
            if tm.owner in own_types:
                if k in CALLS and target in ids and target != mi.id:
                    edges.append((mi.id, target, "", "call"))
                continue
            if k in CALLS or (k == "set" and tm.kind in ("field", "property") and tm.owner not in chain):
                name = short(target) if k in CALLS else short(target) + " (set)"
                used.setdefault(tm.owner, [])
                if name not in used[tm.owner]:
                    used[tm.owner].append(name)
                edges.append((mi.id, "out:" + tm.owner, "" if k in CALLS else "sets", "call" if k in CALLS else "write"))

    def type_node(side: str, full: str, members: list) -> str:
        ext = p.is_external_type(full)
        shown = members[:6] + ([f"+{len(members) - 6} more"] if len(members) > 6 else [])
        head = full + ("  · AI/ external" if ext else "")
        label = f"<b>{esc(head)}</b><br>" + "<br>".join(esc(m) for m in shown)
        nid = mid_node(side + "_" + full)
        mb.node(nid, label, "ext" if ext else "other", status=status.get(side + ":" + full, "same"))
        return nid

    for full, ms in sorted(calling.items()):
        type_node("in", full, ms)
    for full, ms in sorted(used.items()):
        type_node("out", full, ms)
    for a, b, label, style in edges:
        na = mid_node(a.replace(":", "_", 1)) if a.startswith("in:") else mid_node(a)
        nb = mid_node(b.replace(":", "_", 1)) if b.startswith("out:") else mid_node(b)
        mb.edge(na, nb, label, style, status.get(("edge", a, b), "same"))
    return mb.render()


# ----------------------------------------------------------------------------- file page

def _src_link(page: str, src: str, a: int, b: int) -> str:
    return f"[L{a}–{b}]({rel(page, ROOT + '/' + src)}#L{a}-L{b})" if a != b else f"[L{a}]({rel(page, ROOT + '/' + src)}#L{a})"


def _note_block(notes_for: list, page: str, notes_dir_rel: str) -> list:
    out = []
    for n in notes_for:
        out.append("> " + badge(n))
        out.append(">")
        for line in n.text.splitlines():
            out.append("> " + line)
        if n.broken_mentions:
            out.append("> ⛔ mentions ids that don't exist: " + ", ".join(f"`{m}`" for m in n.broken_mentions))
        if n.image and n.image.get("path"):
            out.append(">")
            out.append(f"> ![{n.image.get('alt', '')}]({notes_dir_rel}/{n.image['path']})")
        out.append("")
    return out


def _is_trivial(mi) -> bool:
    f = mi.flow
    kinds = [n.kind for n in f.nodes]
    return kinds.count("block") <= 1 and len(f.nodes) <= 3 and sum(len(n.lines) for n in f.nodes if n.kind == "block") <= 2


def file_page(model: Model, path: str, page: str, notes: list, frame: set, notes_dir_rel: str) -> str:
    fi = model.files[path]
    p = model.project
    by_target: dict[str, list] = {}
    for n in notes:
        by_target.setdefault(n.target, []).append(n)
    mine = sorted(model.file_members(path), key=lambda mi: mi.member.line)
    types = fi.types
    L = [GENERATED, f"# {path}", ""]
    tdesc = " · ".join(f"`{_type_title(model, t)}`" for t in types if t.outer is None)
    L.append(f"{tdesc} · {fi.lines} lines · {len(mine)} code blocks · "
             f"[source]({rel(page, ROOT + '/' + path)}) · [index]({rel(page, 'index.md')})")
    L.append("")
    if fi.external:
        L.append("> This file is in an **external** folder: shown only as the members other files use.")
        L.append("")
    for t in types:
        L += _note_block(by_target.get(t.full, []), page, notes_dir_rel)
        if t.comment and t.outer is None:
            L.append(f"*Code comment on `{t.name}`:* {t.comment}")
            L.append("")
    L.append(f"<sub>{LEGEND}</sub>")
    L.append("")
    # --- map
    map_types = []
    for mi in map_members(model, path):
        if mi.type.full not in map_types:
            map_types.append(mi.type.full)
    for tfull in map_types:
        split = len(map_types) > 1  # one map per class keeps each view near the ~20 node budget
        L.append("## Who calls what" + (f" · {tfull}" if split else ""))
        L.append("")
        L.append("Left: who calls in (Unity included). Middle: its methods. Right: what they call or set elsewhere.")
        L.append("")
        L.append("```mermaid")
        L.append(file_map(model, path, frame, only_type=tfull if split else None))
        L.append("```")
        L.append("")
    # --- state
    for t in types:
        fields = [m for m in t.members if m.kind in ("field", "const", "event", "property", "enum_member")]
        if not fields:
            continue
        L.append(f"## State · {t.kind} {t.name}")
        L.append("")
        if t.kind == "enum":
            L.append("| Value | = | Comment |")
            L.append("|---|---|---|")
            for m in fields:
                L.append(f"| `{m.name}` | {m.init} | {m.comment} |")
            L.append("")
            continue
        L.append("| Member | Type | Inspector | Default / value | Comment / tooltip |")
        L.append("|---|---|---|---|---|")
        for m in fields:
            insp = ""
            if "PlayModeOnly" in m.attrs:
                insp = "play mode only"
            elif "HideInInspector" in m.attrs:
                insp = "hidden"
            elif m.kind == "field" and ("public" in m.mods or "SerializeField" in m.attrs) and not m.is_static and m.kind != "const":
                insp = "✓"
            val = m.init
            if m.kind == "property":
                g = m.accessors.get("get")
                if g is not None and g.stmts and len(g.stmts) == 1 and g.stmts[0].kind == "simple" and not m.accessors.get("set"):
                    val = "=> " + g.stmts[0].text
                kinds = "/".join(k for k in ("get", "set", "init") if k in m.accessors)
                ty = f"{m.type} {{{kinds}}}" if kinds else m.type
            else:
                ty = m.type
            mods = " ".join(x for x in m.mods if x in ("static", "const", "readonly", "override", "virtual", "abstract"))
            note = (m.tooltip or m.comment).replace("|", "\\|")
            shown = ("`" + val.replace("|", "\\|") + "`") if val else ""
            L.append(f"| `{m.name}` | `{(mods + ' ' if mods else '') + ty}` | {insp} | {shown} | {note} |")
        L.append("")
    # --- methods
    if mine:
        L.append("## Methods")
        L.append("")
        L.append("| | Method | Lines | Calls (project) | Called by |")
        L.append("|---|---|---|---|---|")
        for mi in mine:
            calls = sorted({t for k, t in mi.uses if k == "call" and t != mi.id})
            callers = model.callers.get(mi.id, [])
            by = ("Unity · " + UNITY_WHEN.get(mi.member.name, "")) if mi.unity_event else (
                ", ".join(f"`{c}`" for c in callers[:4]) + (f" +{len(callers) - 4}" if len(callers) > 4 else "")
                if callers else "*none in code (Inspector / UnityEvent?)*" if "public" in mi.member.mods else "")
            L.append(f"| {icon(mi, frame).strip()} | [{short(mi.id)}](#{_anchor(mi.id)}) | "
                     f"{_src_link(page, path, mi.member.line, mi.member.end)} | {len(calls)} | {by} |")
        L.append("")
        small = []
        for mi in mine:
            if _is_trivial(mi):
                small.append(mi)
                continue
            L.append(f'<a id="{_anchor(mi.id)}"></a>')
            L.append("")
            L.append(f"### {icon(mi, frame)}{esc_md(mi.title.lstrip('⚡⏳ '))}")
            L.append("")
            meta = [_src_link(page, path, mi.member.line, mi.member.end), f"`{mi.id}`", f"code `{mi.member.fingerprint}`"]
            if mi.overrides:
                meta.append(f"overrides `{mi.overrides}`")
            L.append(" · ".join(meta))
            L.append("")
            if mi.member.comment:
                L.append(f"*Code comment:* {mi.member.comment}")
                L.append("")
            L += _note_block(by_target.get(mi.id, []), page, notes_dir_rel)
            L.append("```mermaid")
            L.append(flow_to_mermaid(mi.flow, unity_event=mi.member.name if mi.unity_event else None,
                                     coroutine=mi.coroutine))
            L.append("```")
            L.append("")
            calls = [("base " if k == "base" else "") + "\0" + t for k, t in mi.uses if k in CALLS and t != mi.id]
            if calls:
                L.append("**Calls:** " + " · ".join(c.split("\0")[0] + _member_link(model, page, c.split("\0")[1])
                                                  for c in dict.fromkeys(calls)))
                L.append("")
        if small:
            L.append("### Short members")
            L.append("")
            L.append("Straight-line members with one or two steps: the whole flow fits in one row.")
            L.append("")
            L.append("| | Member | Lines | Steps |")
            L.append("|---|---|---|---|")
            for mi in small:
                steps = "<br>".join("`" + ln.text.replace("|", "\\|") + "`" for n in mi.flow.nodes if n.kind == "block"
                                    for ln in n.lines) or "*(empty)*"
                L.append(f'| {icon(mi, frame).strip()} | <a id="{_anchor(mi.id)}"></a>{esc_md(mi.title.lstrip("⚡⏳ "))} | '
                         f"{_src_link(page, path, mi.member.line, mi.member.end)} | {steps} |")
            L.append("")
    orphans = [n for n in notes if n.status == "orphaned"]
    if orphans:
        L.append("## Orphaned notes")
        L.append("")
        L.append("These notes point at code that no longer exists. Re-attach or delete them in the notes file.")
        L.append("")
        for n in orphans:
            L.append(f"- `{n.target}`: {n.text[:120]}")
        L.append("")
    return "\n".join(L) + "\n"


def esc_md(s: str) -> str:
    return s.replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")


def _anchor(mid: str) -> str:
    return "m-" + "".join(ch if ch.isalnum() else "-" for ch in mid).strip("-").lower()


def _member_link(model: Model, page: str, target: str) -> str:
    tm = model.project.member_by_id.get(target)
    if tm is None:
        return f"`{target}`"
    t = model.project.types.get(tm.owner)
    if t is None:
        return f"`{target}`"
    if model.project.path_is_external(t.file):
        return f"`{target}` *(AI/, external)*"
    target_page = page_path(t.file)
    here = rel(page, target_page) if target_page != page else ""
    return f"[`{target}`]({here}#{_anchor(target)})"


# ----------------------------------------------------------------------------- index

def folder_of(path: str) -> str:
    d = posixpath.dirname(path)
    return d or "(root)"


def folder_map(model: Model) -> str:
    mb = MapBuilder("LR")
    p = model.project
    sizes: dict[str, list] = {}
    for f in model.files.values():
        sizes.setdefault(folder_of(f.path), [0, 0])
        sizes[folder_of(f.path)][0] += 1
        sizes[folder_of(f.path)][1] += f.lines
    for d, (nf, nl) in sorted(sizes.items()):
        ext = any(p.path_is_external(f) for f in model.files if folder_of(f) == d)
        mb.node(mid_node("F_" + d), f"{esc(d)}<br>{nf} files · {nl} lines", "ext" if ext else "own")
    counts: dict[tuple, int] = {}
    for (a, b), kinds in model.type_deps.items():
        if not kinds & {"calls", "writes", "creates", "inherits"}:
            continue
        fa, fb = folder_of(p.types[a].file), folder_of(p.types[b].file)
        if fa != fb:
            counts[(fa, fb)] = counts.get((fa, fb), 0) + 1
    for (fa, fb), n in sorted(counts.items()):
        mb.edge(mid_node("F_" + fa), mid_node("F_" + fb), f"{n}", "call")
    return mb.render()


def lifecycle_table(model: Model, page: str, pages_written: set) -> list:
    """Which code Unity runs, and when: a class x phase matrix (past ~20 entries a matrix reads better than a graph)."""
    rows: dict[str, dict] = {}
    for mid, mi in sorted(model.members.items()):
        if mi.unity_event and not model.project.is_external_type(mi.type.full):
            ph = UNITY_PHASE.get(mi.member.name, "callback")
            rows.setdefault(mi.type.full, {}).setdefault(ph, []).append(mi)
    phases = [ph for ph in PHASE_ORDER if any(ph in r for r in rows.values())]
    out = ["| Class | " + " | ".join(phases) + " |", "|---|" + "---|" * len(phases)]
    for full in sorted(rows):
        t = model.project.types[full]
        cells = []
        for ph in phases:
            names = []
            for mi in rows[full].get(ph, []):
                if t.file in pages_written:
                    names.append(f"[{mi.member.name}]({rel(page, page_path(t.file))}#{_anchor(mi.id)})")
                else:
                    names.append(mi.member.name)
            cells.append(", ".join(names))
        out.append(f"| `{full}` | " + " | ".join(cells) + " |")
    return out


def index_page(model: Model, page: str, notes_by_file: dict, frame: set, pages_written: set, coverage: tuple) -> str:
    p = model.project
    files = sorted(model.files.values(), key=lambda f: f.path)
    own = [f for f in files if not f.external]
    L = [GENERATED, "# Code graph · Lord of the Dungeon", ""]
    L.append(f"{len(files)} C# files · {sum(f.lines for f in files)} lines · {len(p.types)} types · "
             f"{len(model.members)} code blocks · every statement of your own code is in a flowchart node "
             f"({coverage[0]}/{coverage[1]} statements mapped) · `AI/` is treated as external")
    L.append("")
    L.append(f"<sub>{LEGEND}</sub>")
    L.append("")
    L.append("## Folders")
    L.append("")
    L.append("Arrow number = how many classes in one folder call, set, create or extend classes in the other.")
    L.append("")
    L.append("```mermaid")
    L.append(folder_map(model))
    L.append("```")
    L.append("")
    L.append("## What Unity runs, and when")
    L.append("")
    L.append("Every method Unity calls by itself, by phase. Everything else in the game starts from one of these "
             "(or from a button / UnityEvent wired in a scene, which the code can't show). "
             "*every frame* and *physics* run all the time: changes there cost performance.")
    L.append("")
    L += lifecycle_table(model, page, pages_written)
    L.append("")
    L.append("## Files")
    L.append("")
    L.append("| File | Types | Lines | Code blocks | 🔁 per frame | AI notes |")
    L.append("|---|---|---|---|---|---|")
    for f in files:
        mems = model.file_members(f.path)
        nf = sum(1 for mi in mems if mi.id in frame or mi.unity_event and mi.member.name in PER_FRAME_EVENTS)
        notes = notes_by_file.get(f.path, [])
        if notes:
            cur = sum(1 for n in notes if n.status == "current")
            drift = sum(1 for n in notes if n.status == "drifted")
            orph = sum(1 for n in notes if n.status == "orphaned")
            ns = f"{cur} ✅" + (f" · {drift} ⚠️" if drift else "") + (f" · {orph} ❓" if orph else "")
        else:
            ns = ""
        name = f"[{f.path}]({rel(page, page_path(f.path))})" if f.path in pages_written else f.path
        if f.external:
            name += " *(external)*"
        tnames = ", ".join(t.name for t in f.types if t.outer is None)
        L.append(f"| {name} | {tnames} | {f.lines} | {len(mems)} | {nf or ''} | {ns} |")
    L.append("")
    return "\n".join(L) + "\n"
