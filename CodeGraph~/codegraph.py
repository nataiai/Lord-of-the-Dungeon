def base_type_name(t):
    """'List<Image>' -> 'List', 'Image[]' -> 'Image', 'BuffEffect.Buff?' -> 'BuffEffect.Buff'."""
    if not t:
        return ''
    t = re.sub(r'\s+', '', t)
    i = t.find('<')
    if i >= 0:
        t = t[:i]
    return re.sub(r'(\[[,]*\]|\?|\*)+$', '', t)


def generic_args(t):
    t = re.sub(r'\s+', '', t or '')
    i, j = t.find('<'), t.rfind('>')
    if i < 0 or j < i:
        return []
    out, depth, start = [], 0, i + 1
    for k in range(i + 1, j):
        c = t[k]
        if c in '<([':
            depth += 1
        elif c in '>)]':
            depth -= 1
        elif c == ',' and depth == 0:
            out.append(t[start:k])
            start = k + 1
    out.append(t[start:j])
    return out


def elem_type(t):
    if not t:
        return None
    t = re.sub(r'\s+', '', t).rstrip('?')
    if t.endswith(']'):
        return t[:t.rfind('[')]
    args = generic_args(t)
    if args:
        return args[-1]
    return 'char' if t == 'string' else None


def type_names_in(t):
    """Every type name mentioned in a type text: 'Dictionary<RoomTrigger,RoomTrigger>' -> [...]."""
    return re.findall(r'[A-Za-z_][\w.]*', re.sub(r'\b(in|out|ref)\b', '', t or ''))


