def overview_data(proj, captions):
    """Classes that call each other. Arrows: calls (solid) and inherits (thick).
    Also returns the classes left out because nothing calls them and they call nothing."""
    d = GData('LR')
    order = {td: i for i, td in enumerate(proj.types)}
    edges = []
    for td in proj.types:
        if td.kind == 'enum':
            continue
        uses = proj.type_uses(td)
        for t2 in sorted(uses, key=lambda x: order.get(x, 0)):
            if t2.kind != 'enum' and uses[t2] != 'uses':
                edges.append((td, t2, uses[t2]))
    linked = {x for a, b, _ in edges for x in (a, b)}
    left_out = [td for td in proj.types if td.kind != 'enum' and td not in linked]
    for td in proj.types:
        if td in linked:
            lines = [td.full] + ([captions[td]] if captions.get(td) else [])
            d.node('t_' + sid(td.full), 'block', lines, 'ext' if td.file.external else None, 40)
    for a, b, kind in edges:
        d.edge('t_' + sid(a.full), 't_' + sid(b.full), '', 'thick' if kind == 'inherits' else '')
    return d, left_out


