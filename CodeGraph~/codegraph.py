def posix_dir(path):
    return path.rsplit('/', 1)[0] if '/' in path else ''


LINK_RE = re.compile(r'(!?\[[^\]]*\]\()([^)\s]+)(\))|(<img\b[^>]*?\bsrc=")([^"]+)(")')


def rewrite_links(text, note_dir, page_dir):
    """Links in a note are relative to the note; make them relative to the page that shows it."""
    def fix(target):
        if re.match(r'^([a-z]+:|#|/)', target):
            return target
        from urllib.parse import unquote
        return qlink(relpath(normpath_posix((note_dir + '/' if note_dir else '') + unquote(target)), page_dir))

    def sub(m):
        if m.group(1):
            return m.group(1) + fix(m.group(2)) + m.group(3)
        return m.group(4) + fix(m.group(5)) + m.group(6)
    return LINK_RE.sub(sub, text)


def normpath_posix(p):
    import posixpath
    return posixpath.normpath(p)


