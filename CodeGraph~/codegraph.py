def is_under(path, prefixes):
    low = path.lower()
    return any(low == p.lower().rstrip('/') or low.startswith(p.lower().rstrip('/') + '/') for p in prefixes)


def parse_source(path, src, external):
    f = CsFile(path, src.replace('\r\n', '\n').replace('\r', '\n'), external)
    f.lines = f.src.count('\n') + (0 if f.src.endswith('\n') else 1)
    try:
        f.parser = Parser(f)
        f.parser.parse_file()
        attach_comments(f)
    except (ParseError, IndexError, RecursionError) as e:
        f.error = str(e) or e.__class__.__name__
        f.types, f.all_types = [], []
    for t in f.toks:
        f.code_lines.update(range(t.line, t.end_line + 1))
    for td in f.all_types:
        for mem in td.members:
            mark_stmt_cover(f, mem)
    return f


def mark_stmt_cover(f, mem):
    p = f.parser
    p.cover(mem.a, mem.head_b)
    for s in member_stmts(mem):
        p.cover(s.a, s.b)
    for acc in mem.accessors:
        p.cover(acc.a, acc.b)
    if mem.body is not None or mem.expr is not None:
        p.cover(mem.a, mem.b)


def list_sources(cfg):
    root = cfg['root_abs']
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith('.') and not d.endswith('~'))
        for fn in filenames:
            if fn.endswith('.cs') and not fn.startswith('.'):
                rel = os.path.relpath(os.path.join(dirpath, fn), root).replace(os.sep, '/')
                if not is_under(rel, cfg['ignore']):
                    out.append(rel)
    return sorted(out)


