HASH_RE = re.compile(r'<!--\s*([0-9a-f]{6})\s*-->')


@dataclass(eq=False)
class Note:
    key: str
    text: str
    hash: str
    line: int


def parse_note_file(text):
    """'# Title' and the text under it: the file's note. Each '## Key' section: the note of a class or method."""
    lines = text.replace('\r\n', '\n').split('\n')
    file_note = Note('', '', '', 1)
    sections, cur, buf, fence = {}, file_note, [], False
    for i, ln in enumerate(lines, 1):
        if ln.lstrip().startswith('```'):
            fence = not fence
        if not fence and i == 1 and ln.startswith('# '):
            m = HASH_RE.search(ln)
            file_note.hash = m.group(1) if m else ''
            continue
        if not fence and ln.startswith('## '):
            cur.text = '\n'.join(buf).strip()
            m = HASH_RE.search(ln)
            key = HASH_RE.sub('', ln[3:]).strip().strip('`').strip()
            cur, buf = Note(key, '', m.group(1) if m else '', i), []
            sections[key] = cur
            continue
        buf.append(ln)
    cur.text = '\n'.join(buf).strip()
    return file_note, sections


def load_notes(notes_dir):
    notes = {}
    if not os.path.isdir(notes_dir):
        return notes
    for dirpath, dirnames, filenames in os.walk(notes_dir):
        dirnames.sort()
        for fn in sorted(filenames):
            if fn.endswith('.md'):
                path = os.path.join(dirpath, fn)
                rel = os.path.relpath(path, notes_dir).replace(os.sep, '/')
                notes[rel[:-3]] = parse_note_file(read_text(path))
    return notes


def first_line(note):
    if not note or not note.text:
        return ''
    ln = note.text.strip().split('\n')[0].strip()
    return '' if ln.startswith(('!', '<', '|', '```', '#', '-', '*')) else ln


def type_fp(td):
    p = td.file.parser
    return short_hash(' '.join([p.text(td.a, td.head_b)] + [p.text(m.a, m.head_b) for m in td.members]))


def file_fp(f):
    return short_hash(' '.join('%s:%s:%s' % (td.kind, td.full, ','.join(td.bases)) for td in f.all_types))


