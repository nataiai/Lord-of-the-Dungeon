def slug(heading):
    """GitHub's anchor for a heading."""
    h = heading.strip().lower()
    h = re.sub(r'[^\w\- ]', '', h)
    return h.replace(' ', '-')


def qlink(path):
    from urllib.parse import quote
    return quote(path)


def relpath(to, frm_dir):
    import posixpath
    return posixpath.relpath(to, frm_dir or '.')


class Site:
    """Everything one generation needs: the parsed code, the notes, and where pages go."""

    def __init__(self, cfg, proj, notes, tool_rel):
        self.cfg, self.proj, self.notes, self.tool = cfg, proj, notes, tool_rel
        self.graphs = tool_rel + '/' + cfg['graphs']
        self.notes_rel = tool_rel + '/' + cfg['notes']
        self.has_chart = {u for u in proj.units if u.shown and not u.trivial and not u.file.external}

    def page_of(self, f):
        return '%s/%s.md' % (self.graphs, f.path)

    def type_heading(self, td):
        return '%s %s' % (td.kind, td.full)

    def link_unit(self, u, from_dir):
        if u.file.external:
            return qlink(relpath(u.file.path, from_dir)) + '#L%d' % u.line
        page = qlink(relpath(self.page_of(u.file), from_dir))
        anchor = slug(u.key) if u in self.has_chart else slug(self.type_heading(u.owner))
        return page + '#' + anchor

    def note_for(self, f):
        return self.notes.get(f.path, (Note('', '', '', 0), {}))

    def note_md(self, note, expected, page_dir, note_path):
        if note is None or not note.text:
            return []
        text = rewrite_links(note.text, posix_dir(note_path), page_dir)
        out = []
        if note.hash and note.hash != expected:
            out += ['*⚠️ This note was written for older code and may be out of date.*', '']
        return out + [text, '']

    def mermaid(self, code):
        return ['```mermaid', code, '```', '']

    def chart(self, u):
        try:
            return self.mermaid(Flow(u).build())
        except (IndexError, KeyError, ValueError, RecursionError, AttributeError, TypeError) as e:
            p = u.owner.file.parser
            return ['> ⚠️ No flowchart (%s), so here is the code:' % e.__class__.__name__, '',
                    '```csharp', '\n'.join(t for _, t in p.lines(u.a, u.b)), '```', '']

    def info_line(self, u, page_dir):
        src = qlink(relpath(u.file.path, page_dir))
        parts = ['[lines %d–%d](%s#L%d-L%d)' % (u.line, u.end_line, src, u.line, u.end_line)]
        callers = [(c, '') for c, _ in u.callers if c.shown] + [(c, ' (virtual)') for c, _ in u.vcallers if c.shown]
        if is_message(self.proj, u):
            parts.append('called by Unity: ' + UNITY_MESSAGES[u.member.name])
        if callers:
            seen, items = set(), []
            for c, tag in sorted(callers, key=lambda x: x[0].key):
                if c not in seen:
                    seen.add(c)
                    items.append('[%s](%s)%s' % (c.key, self.link_unit(c, page_dir), tag))
            parts.append('called by ' + ', '.join(items))
        calls, seen = [], set()
        for t, lab in u.calls:
            if t.shown and t not in seen:
                seen.add(t)
                calls.append('[%s](%s)%s' % (t.key, self.link_unit(t, page_dir), ' (%s)' % lab if lab else ''))
        if calls:
            parts.append('calls ' + ', '.join(calls))
        return '<sub>' + ' · '.join(parts) + '</sub>'

    def file_page(self, f):
        page = self.page_of(f)
        page_dir = posix_dir(page)
        note_path = '%s/%s.md' % (self.notes_rel, f.path)
        fnote, sections = self.note_for(f)
        out = ['%s from %s. Do not edit: run python "CodeGraph~/codegraph.py". Notes go in %s -->'
               % (GENERATED_MARK, f.path, note_path), '# ' + f.path, '']
        meta = ['[overview](%s)' % qlink(relpath(self.graphs + '/README.md', page_dir)),
                '[source](%s)' % qlink(relpath(f.path, page_dir)), '%d lines' % f.lines]
        if f.usings:
            meta.append('using ' + ', '.join('`%s`' % x for x in f.usings))
        out += [' · '.join(meta), '']
        out += self.note_md(fnote, file_fp(f), page_dir, note_path)
        if f.error:
            out += ['> ⚠️ CodeGraph could not read this file (%s), so here it is as text:' % f.error, '',
                    '```csharp', f.src.rstrip(), '```', '']
        for td in f.all_types:
            out += ['## ' + self.type_heading(td), '']
            out += self.note_md(sections.get(td.full), type_fp(td), page_dir, note_path)
            out += self.mermaid(type_graph(self.proj, td))
            for u in self.proj.units_of_type.get(td, []):
                if u not in self.has_chart:
                    continue
                out += ['### ' + u.key, '']
                out += self.note_md(sections.get(u.key), u.fp, page_dir, note_path)
                out += self.chart(u)
                out += [self.info_line(u, page_dir), '']
        missing = sorted(f.code_lines - f.covered)
        if missing:
            out += ['<sub>⚠️ Lines not in any graph: %s</sub>' % ', '.join(map(str, missing)), '']
        return '\n'.join(out).rstrip() + '\n'

    def captions(self):
        caps = {}
        for f in self.proj.files:
            _, sections = self.note_for(f)
            for td in f.all_types:
                c = first_line(sections.get(td.full))
                if c and len(c) <= 70:
                    caps[td] = c
        return caps

    def index_page(self, status):
        page = self.graphs + '/README.md'
        page_dir = posix_dir(page)
        out = ['%s. Do not edit: run python "CodeGraph~/codegraph.py". Notes go in %s -->'
               % (GENERATED_MARK, self.notes_rel), '# Code graphs', '',
               'Every line of C# in this folder, drawn by [codegraph.py](%s) as graphs: one page per `.cs` file, '
               'a graph per class and a flowchart per method. The text and pictures between the graphs are written '
               'by the AI (or you) in [%s/](%s). [How to read](#how-to-read-the-graphs) · '
               '[How to update](%s)' % (qlink(relpath(self.tool + '/codegraph.py', page_dir)), self.cfg['notes'],
                                        qlink(relpath(self.notes_rel, page_dir)),
                                        qlink(relpath(self.tool + '/README.md', page_dir))), '']
        proj_note = self.notes.get('README')
        if proj_note:
            fnote, sections = proj_note
            out += self.note_md(fnote, fnote.hash, page_dir, self.notes_rel + '/README.md')
            for key, n in sections.items():
                out += ['## ' + key, ''] + self.note_md(n, n.hash, page_dir, self.notes_rel + '/README.md')
        data, left_out = overview_data(self.proj, self.captions())
        out += ['## Who calls whom', ''] + self.mermaid(render(data))
        out += ['<sub>Arrow: calls. Thick arrow: inherits. Gray dashed: external (%s). Not drawn, because they call '
                'no other class and none calls them: %s.</sub>' % (', '.join(self.cfg['external']) or 'none',
                                                                   ', '.join(t.full for t in left_out)), '']
        out += ['## What Unity calls, and when', '', '| When | Classes |', '|---|---|']
        events = {}
        for u in self.proj.units:
            if u.shown and is_message(self.proj, u):
                events.setdefault(u.member.name, []).append(u)
        for name in UNITY_MESSAGES:
            if name in events:
                links = ['[%s](%s)' % (u.owner.full, self.link_unit(u, page_dir)) for u in events[name]]
                out.append('| %s (`%s`) | %s |' % (UNITY_MESSAGES[name], name, ', '.join(links)))
        out.append('')
        for ext in (False, True):
            rows = [f for f in self.proj.files if f.external == ext]
            if not rows:
                continue
            out += ['## ' + ('External files (%s): drawn as outside boxes only' % ', '.join(self.cfg['external'])
                             if ext else 'Files'), '',
                    '| File | Types | Lines | About |', '|---|---|---|---|']
            for f in rows:
                target = f.path if ext else self.page_of(f)
                types = ', '.join(('enum ' if t.kind == 'enum' else '') + t.full for t in f.all_types)
                fnote = self.note_for(f)[0]
                out.append('| [%s](%s) | %s | %d | %s |' % (f.path, qlink(relpath(target, page_dir)), types, f.lines,
                                                            first_line(fnote).replace('|', '\\|')))
            out.append('')
        out += HOW_TO_READ + [''] + ['## Status', ''] + status + ['']
        return '\n'.join(out).rstrip() + '\n'


