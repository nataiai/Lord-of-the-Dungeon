def load_config():
    cfg = dict(DEFAULTS)
    path = os.path.join(HERE, 'codegraph.json')
    if os.path.exists(path):
        with open(path, encoding='utf-8') as f:
            cfg.update({k: v for k, v in json.load(f).items() if not k.startswith('_')})
    cfg['root_abs'] = os.path.normpath(os.path.join(HERE, cfg['root']))
    return cfg


def short_hash(text, n=6):
    return hashlib.sha1(text.encode('utf-8')).hexdigest()[:n]


# =============================================================== tokenizer

@dataclass
class Tok:
    kind: str     # id num str chr op
    text: str
    start: int
    end: int
    gap: bool     # whitespace or a comment right before it
    line: int = 0
    end_line: int = 0


@dataclass
class Comment:
    text: str
    start: int
    end: int
    line: int
    own_line: bool   # nothing but spaces before it on its line
    pp: bool = False  # preprocessor line (#if ...)
    used: bool = False


ID_RE = re.compile(r'@?[^\W\d]\w*')
NUM_RE = re.compile(r'(?:0[xX][0-9a-fA-F_]+|0[bB][01_]+|\d[\d_]*(?:\.\d[\d_]*)?(?:[eE][+-]?\d+)?'
                    r'|\.\d[\d_]*(?:[eE][+-]?\d+)?)[a-zA-Z]*')
OPS = ['??=', '<<=', '=>', '==', '!=', '<=', '>=', '&&', '||', '++', '--', '+=', '-=', '*=', '/=', '%=',
       '&=', '|=', '^=', '<<', '->', '::', '??', '?.', '..']


def scan_string(s, i):
    """End index of the string or char literal starting at i, or None if none starts there."""
    n, j = len(s), i
    interp = verb = False
    while j < n and s[j] in '$@' and j - i < 3:
        interp |= s[j] == '$'
        verb |= s[j] == '@'
        j += 1
    if j >= n or s[j] not in '"\'':
        return None
    if s[j] == "'":
        if interp or verb:
            return None
        j += 1
        while j < n and s[j] != "'" and s[j] != '\n':
            j += 2 if s[j] == '\\' else 1
        return min(j + 1, n)
    j += 1
    while j < n:
        ch = s[j]
        if verb and ch == '"':
            if j + 1 < n and s[j + 1] == '"':
                j += 2
                continue
            return j + 1
        if not verb:
            if ch == '\\':
                j += 2
                continue
            if ch == '"':
                return j + 1
            if ch == '\n':
                return j
        if interp and ch == '{':
            if j + 1 < n and s[j + 1] == '{':
                j += 2
                continue
            j = scan_hole(s, j + 1)
            continue
        j += 1
    return n


def scan_hole(s, j):
    depth, n = 1, len(s)
    while j < n:
        ch = s[j]
        if ch in '"\'$@':
            k = scan_string(s, j)
            if k:
                j = k
                continue
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
            if depth == 0:
                return j + 1
        j += 1
    return n


def tokenize(src):
    toks, comments = [], []
    line_starts = [0] + [m.end() for m in re.finditer('\n', src)]

    def line_of(off):
        return bisect.bisect_right(line_starts, off)

    i, n = 0, len(src)
    gap, line_start = True, True
    while i < n:
        c = src[i]
        if c == '\n':
            i += 1
            gap = line_start = True
            continue
        if c in ' \t\r\f\v﻿':
            i += 1
            gap = True
            continue
        if c == '#' and line_start:
            j = src.find('\n', i)
            j = n if j < 0 else j
            comments.append(Comment(src[i:j].strip(), i, j, line_of(i), True, pp=True))
            i, gap = j, True
            continue
        if src.startswith('//', i):
            j = src.find('\n', i)
            j = n if j < 0 else j
            text = src[i + 2:j].strip()
            if text.startswith('/'):
                text = text[1:].strip()
            comments.append(Comment(text, i, j, line_of(i), line_start))
            i, gap = j, True
            continue
        if src.startswith('/*', i):
            j = src.find('*/', i + 2)
            j = n if j < 0 else j + 2
            body = ' '.join(x.strip().lstrip('*').strip() for x in src[i + 2:j - 2].split('\n')).strip()
            comments.append(Comment(body, i, j, line_of(i), line_start))
            i, gap = j, True
            continue
        line_start = False
        j = scan_string(src, i) if c in '"\'$@' else None
        if j:
            kind = 'chr' if src[i] == "'" else 'str'
        else:
            m = ID_RE.match(src, i)
            if m:
                j, kind = m.end(), 'id'
            else:
                m = NUM_RE.match(src, i) if (c.isdigit() or (c == '.' and i + 1 < n and src[i + 1].isdigit())) else None
                if m:
                    j, kind = m.end(), 'num'
                else:
                    kind = 'op'
                    j = i + 1
                    for op in OPS:
                        if src.startswith(op, i):
                            if op == '?.' and i + 2 < n and src[i + 2].isdigit():
                                continue
                            j = i + len(op)
                            break
        toks.append(Tok(kind, src[i:j], i, j, gap, line_of(i), line_of(j - 1)))
        gap = False
        i = j
    return toks, comments


class ParseError(Exception):
    pass


def match_brackets(toks):
    match = [-1] * len(toks)
    stack = []
    pairs = {')': '(', ']': '[', '}': '{'}
    for k, t in enumerate(toks):
        if t.kind != 'op':
            continue
        if t.text in '([{':
            stack.append(k)
        elif t.text in ')]}':
            if not stack or toks[stack[-1]].text != pairs[t.text]:
                raise ParseError('unbalanced "%s" on line %d' % (t.text, t.line))
            o = stack.pop()
            match[o], match[k] = k, o
    if stack:
        raise ParseError('"%s" on line %d is never closed' % (toks[stack[-1]].text, toks[stack[-1]].line))
    return match


# =============================================================== model

TYPE_KWS = {'class', 'struct', 'interface', 'enum', 'record'}
MODIFIERS = {'public', 'private', 'protected', 'internal', 'static', 'readonly', 'const', 'virtual', 'override',
             'abstract', 'sealed', 'new', 'extern', 'unsafe', 'volatile', 'async', 'partial', 'event', 'required',
             'implicit', 'explicit', 'file', 'ref'}
BUILTIN_TYPES = {'int', 'float', 'double', 'bool', 'string', 'char', 'byte', 'sbyte', 'short', 'ushort', 'uint',
                 'long', 'ulong', 'decimal', 'object', 'void', 'var', 'dynamic', 'nint', 'nuint'}
KEYWORDS = {'if', 'else', 'for', 'foreach', 'while', 'do', 'switch', 'case', 'default', 'try', 'catch', 'finally',
            'return', 'throw', 'break', 'continue', 'goto', 'yield', 'using', 'lock', 'fixed', 'new', 'this', 'base',
            'typeof', 'sizeof', 'nameof', 'checked', 'unchecked', 'unsafe', 'true', 'false', 'null', 'in', 'is', 'as',
            'out', 'ref', 'params', 'operator', 'delegate', 'event', 'class', 'struct', 'interface', 'enum',
            'namespace', 'static', 'const', 'readonly', 'stackalloc', 'when', 'where', 'not', 'and', 'or', 'with',
            'await', 'public', 'private', 'protected', 'internal', 'virtual', 'override', 'abstract', 'sealed',
            'extern', 'volatile', 'implicit', 'explicit', 'get', 'set', 'init', 'add', 'remove', 'value', 'global'}


def is_ident(t):
    return bool(t) and (t[0].isalpha() or t[0] in '_@') and t not in KEYWORDS


def is_type_start(t):
    return t in BUILTIN_TYPES or is_ident(t)


@dataclass(eq=False)
class Stmt:
    kind: str          # simple if for foreach while do switch try using lock block return throw break continue
    a: int             # yield yieldbreak goto label localfunc empty unsafe checked
    b: int             # token span [a, b)
    ha: int = 0        # main text span (condition, header, or the statement without ';')
    hb: int = 0
    kids: List['Stmt'] = field(default_factory=list)   # body (loops, using, lock, block, label)
    then: Optional[List['Stmt']] = None
    els: Optional[List['Stmt']] = None
    sections: Optional[list] = None   # switch: [(labels, stmts)]
    catches: Optional[list] = None    # try: [(header, stmts)]
    fin: Optional[List['Stmt']] = None
    local: Optional['Member'] = None
    lead: List[str] = field(default_factory=list)
    trail: List[str] = field(default_factory=list)
    text: str = ''
    line: int = 0
    end_line: int = 0


@dataclass(eq=False)
class Accessor:
    kind: str                 # get set init add remove
    a: int
    b: int
    mods: List[str]
    body: Optional[List[Stmt]] = None
    expr: Optional[Stmt] = None


@dataclass(eq=False)
class Member:
    kind: str                 # field property method ctor dtor event indexer operator enum delegate
    name: str
    type: str                 # field/property type, return type ('' for ctors)
    a: int
    b: int
    owner: 'TypeDecl' = None
    mods: List[str] = field(default_factory=list)
    attrs: List[str] = field(default_factory=list)
    params: List[Tuple[str, str, bool]] = field(default_factory=list)   # (type, name, has default)
    params_text: str = ''
    body: Optional[List[Stmt]] = None
    expr: Optional[Stmt] = None
    accessors: List[Accessor] = field(default_factory=list)
    names: List[str] = field(default_factory=list)   # all names of a multi-name field
    head_b: int = 0           # end of the declaration head (before body / accessors)
    lead: List[str] = field(default_factory=list)
    trail: List[str] = field(default_factory=list)
    line: int = 0
    end_line: int = 0
    locals_of: Optional['Member'] = None   # local function: the member it is declared in


@dataclass(eq=False)
class TypeDecl:
    kind: str
    name: str
    full: str
    a: int
    b: int
    head_b: int
    bases: List[str]
    mods: List[str]
    attrs: List[str]
    file: 'CsFile' = None
    outer: Optional['TypeDecl'] = None
    members: List[Member] = field(default_factory=list)
    nested: List['TypeDecl'] = field(default_factory=list)
    lead: List[str] = field(default_factory=list)
    trail: List[str] = field(default_factory=list)
    line: int = 0
    end_line: int = 0


@dataclass(eq=False)
class CsFile:
    path: str
    src: str
    external: bool
    toks: List[Tok] = field(default_factory=list)
    comments: List[Comment] = field(default_factory=list)
    usings: List[str] = field(default_factory=list)
    types: List[TypeDecl] = field(default_factory=list)
    all_types: List[TypeDecl] = field(default_factory=list)
    error: Optional[str] = None
    lines: int = 0
    code_lines: set = field(default_factory=set)
    covered: set = field(default_factory=set)
    parser: 'Parser' = None


# =============================================================== parser

class Parser:
    def __init__(self, f: CsFile):
        self.f = f
        self.toks, self.comments = tokenize(f.src)
        f.toks, f.comments = self.toks, self.comments
        self.m = match_brackets(self.toks)
        self.n = len(self.toks)

    # ---- helpers
    def t(self, k):
        return self.toks[k].text if 0 <= k < self.n else ''

    def text(self, a, b):
        out = []
        for k in range(a, min(b, self.n)):
            tk = self.toks[k]
            if out and tk.gap:
                out.append(' ')
            out.append(tk.text.replace('\n', ' '))
        return ''.join(out)

    def lines(self, a, b):
        """Tokens [a, b) as source lines: [(line, text)]."""
        out = []
        for k in range(a, min(b, self.n)):
            tk = self.toks[k]
            if out and out[-1][0] == tk.line:
                out[-1][1].append((' ' if tk.gap else '') + tk.text)
            else:
                out.append((tk.line, [tk.text]))
        return [(ln, ''.join(parts).replace('\n', ' ')) for ln, parts in out]

    def line(self, k):
        return self.toks[min(k, self.n - 1)].line if self.n else 0

    def semicolon(self, k, b):
        """Index of the ';' ending the statement that starts at k (brackets skipped)."""
        while k < b:
            t = self.toks[k]
            if t.kind == 'op':
                if t.text in '([{':
                    k = self.m[k] + 1
                    continue
                if t.text == ';':
                    return k
            k += 1
        return b

    def skip_angle(self, k):
        """k at '<' of generic arguments: index after the matching '>', or None if it is a less-than."""
        depth = 0
        while k < self.n:
            t = self.t(k)
            if t == '<':
                depth += 1
            elif t == '>':
                depth -= 1
                if depth == 0:
                    return k + 1
            elif t in ('(', '['):
                k = self.m[k]
            elif not (is_type_start(t) or t in (',', '.', '?', '::', '*')):
                return None
            k += 1
        return None

    def skip_type(self, k):
        t = self.t(k)
        if t == '(':
            k = self.m[k] + 1
        elif is_type_start(t):
            k += 1
            while True:
                if self.t(k) == '<':
                    e = self.skip_angle(k)
                    if e is None:
                        return None
                    k = e
                if self.t(k) in ('.', '::') and is_type_start(self.t(k + 1)):
                    k += 2
                    continue
                break
        else:
            return None
        while True:
            t = self.t(k)
            if t == '?' or t == '*':
                k += 1
            elif t == '[' and self.t(k + 1) in (']', ','):
                k = self.m[k] + 1
            else:
                return k

    def split_commas(self, a, b, angle=False):
        parts, depth, start, k = [], 0, a, a
        while k < b:
            t = self.t(k)
            if t in ('(', '[', '{'):
                k = self.m[k] + 1
                continue
            if angle and t == '<':
                depth += 1
            elif angle and t == '>':
                depth -= 1
            elif t == ',' and depth <= 0:
                parts.append((start, k))
                start = k + 1
            k += 1
        if start < b:
            parts.append((start, b))
        return parts

    # ---- file level
    def parse_file(self):
        self.parse_namespace(0, self.n, None)

    def parse_namespace(self, a, b, outer):
        k = a
        while k < b:
            t = self.t(k)
            if t == ';':
                k += 1
            elif t == 'using' or (t == 'global' and self.t(k + 1) == 'using'):
                e = self.semicolon(k, b)
                self.f.usings.append(self.text(k + (2 if t == 'global' else 1), e))
                self.cover(k, e + 1)
                k = e + 1
            elif t == 'namespace':
                j = k + 1
                while j < b and self.t(j) not in ('{', ';'):
                    j += 1
                self.cover(k, j + 1)
                if self.t(j) == '{':
                    self.parse_namespace(j + 1, self.m[j], outer)
                    self.cover(self.m[j], self.m[j] + 1)
                    k = self.m[j] + 1
                else:
                    k = j + 1
            elif t == '[' and self.t(k + 1) == 'assembly':
                k = self.m[k] + 1
            elif self.t(self.attrs_mods(k)[2]) == 'delegate':
                e = self.semicolon(k, b)
                j = self.attrs_mods(k)[2]
                q = j
                while q < e and self.t(q) != '(':
                    q += 1
                name = self.t(q - 1)
                td = TypeDecl('delegate', name, name, k, e + 1, e, [], [], [], self.f, None, line=self.line(k))
                td.end_line = self.line(e)
                self.f.all_types.append(td)
                self.f.types.append(td)
                self.cover(k, e + 1)
                k = e + 1
            else:
                td, k2 = self.parse_type(k, b, outer)
                if td is None:   # top-level statement or something unknown: skip it
                    e = self.semicolon(k, b)
                    k2 = e + 1
                else:
                    self.f.types.append(td)
                k = max(k2, k + 1)

    def attrs_mods(self, k):
        attrs, mods = [], []
        while self.t(k) == '[':
            attrs.append(self.text(k, self.m[k] + 1))
            k = self.m[k] + 1
        while self.t(k) in MODIFIERS:
            if self.t(k) == 'new' and self.t(k + 1) in ('(', '[', '{'):
                break
            mods.append(self.t(k))
            k += 1
        return attrs, mods, k

    def parse_type(self, start, b, outer):
        attrs, mods, k = self.attrs_mods(start)
        kind = self.t(k)
        if kind not in TYPE_KWS:
            return None, start
        k += 1
        if kind == 'record' and self.t(k) in ('class', 'struct'):
            k += 1
        name = self.t(k)
        k += 1
        if self.t(k) == '<':
            k = self.skip_angle(k) or k + 1
        if self.t(k) == '(':
            k = self.m[k] + 1
        bases = []
        if self.t(k) == ':':
            j = k + 1
            while j < b and self.t(j) not in ('{', ';', 'where'):
                j += 1
            bases = [self.text(x, y) for x, y in self.split_commas(k + 1, j, angle=True)]
            k = j
        while k < b and self.t(k) not in ('{', ';'):
            k += 1
        full = (outer.full + '.' if outer else '') + name
        td = TypeDecl(kind, name, full, start, k, k, bases, mods, attrs, self.f, outer,
                      line=self.line(start))
        self.f.all_types.append(td)
        self.cover(start, k + 1)
        if self.t(k) == '{':
            e = self.m[k]
            if kind == 'enum':
                self.parse_enum(k + 1, e, td)
            else:
                self.parse_members(k + 1, e, td)
            self.cover(e, e + 1)
            k = e + 1
        else:
            k += 1
        if self.t(k) == ';':
            k += 1
        td.b = k
        td.end_line = self.line(k - 1)
        return td, k

    def parse_enum(self, a, b, td):
        for x, y in self.split_commas(a, b):
            attrs, _, k = self.attrs_mods(x)
            if k < y:
                mem = Member('enum', self.t(k), td.name, x, y, td, attrs=attrs, head_b=y, line=self.line(x),
                             end_line=self.line(y - 1))
                td.members.append(mem)
                self.cover(x, y + 1 if self.t(y) == ',' else y)

    def parse_members(self, a, b, td):
        k = a
        while k < b:
            if self.t(k) == ';':
                self.cover(k, k + 1)
                k += 1
                continue
            start = k
            nested, k2 = self.parse_type(k, b, td)
            if nested:
                td.nested.append(nested)
                k = k2
                continue
            mem, k2 = self.parse_member(start, b, td)
            if mem:
                td.members.append(mem)
                self.cover(mem.a, mem.head_b)
            k = max(k2, k + 1)

    def parse_member(self, start, b, td):
        attrs, mods, k = self.attrs_mods(start)
        t = self.t(k)
        if t == 'delegate':
            e = self.semicolon(k, b)
            nm = self.t(e - 1)
            j = k + 1
            while j < e and self.t(j) != '(':
                j += 1
            mem = Member('delegate', self.t(j - 1) if j < e else nm, self.text(k + 1, j - 1), start, e + 1, td,
                         mods, attrs, head_b=e + 1)
            return self.finish(mem), e + 1
        if t == '~' and self.t(k + 2) == '(':
            kind, name, rtype, j = 'dtor', '~' + self.t(k + 1), '', k + 2
        elif t == td.name and self.t(k + 1) == '(':
            kind, name, rtype, j = 'ctor', t, '', k + 1
        elif t == 'operator' or (t in ('implicit', 'explicit')):
            j = k
            while j < b and self.t(j) != '(':
                j += 1
            kind, name, rtype = 'operator', self.text(k, j), ''
        else:
            e = self.skip_type(k)
            if e is None:
                e2 = self.semicolon(k, b)
                return None, e2 + 1
            rtype = self.text(k, e)
            if self.t(e) == 'this' and self.t(e + 1) == '[':
                kind, name, j = 'indexer', 'this[]', e + 1
            elif self.t(e) == 'operator':
                j = e
                while j < b and self.t(j) != '(':
                    j += 1
                kind, name = 'operator', 'operator ' + self.text(e + 1, j)
            elif is_ident(self.t(e)) or self.t(e) in ('get', 'set', 'value', 'add', 'remove', 'init', 'when'):
                j = e + 1
                while self.t(j) == '.' and is_ident(self.t(j + 1)):
                    j += 2
                name = self.text(e, j)
                if self.t(j) == '<':
                    j = self.skip_angle(j) or j
                nt = self.t(j)
                if nt == '(':
                    kind = 'event' if 'event' in mods else 'method'
                elif nt == '{':
                    kind = 'event' if 'event' in mods else 'property'
                elif nt == '=>':
                    kind = 'property'
                else:
                    kind = 'event' if 'event' in mods else 'field'
            else:
                e2 = self.semicolon(k, b)
                return None, e2 + 1
        mem = Member(kind, name, rtype, start, start, td, mods, attrs)
        if kind == 'field' or (kind == 'event' and self.t(j) != '{'):
            e = self.semicolon(j, b)
            mem.names = [name]
            for x, y in self.split_commas(j, e)[1:]:
                if is_ident(self.t(x)) and self.t(x + 1) in ('=', ''):
                    mem.names.append(self.t(x))
                elif is_ident(self.t(x)) and x + 1 == y:
                    mem.names.append(self.t(x))
            mem.b = mem.head_b = e + 1
            return self.finish(mem), e + 1
        if kind == 'property' or kind == 'event' or (kind == 'indexer' and self.t(self.m[j] + 1) in ('{', '=>')):
            if kind == 'indexer':
                mem.params_text = self.text(j + 1, self.m[j])
                mem.params = self.parse_params(j + 1, self.m[j])
                j = self.m[j] + 1
            if self.t(j) == '=>':
                e = self.semicolon(j + 1, b)
                mem.head_b = j
                acc = Accessor('get', j, e + 1, [])
                acc.expr = self.simple_stmt(j + 1, e, 'expr')
                mem.accessors.append(acc)
                mem.b = e + 1
                return self.finish(mem), e + 1
            mem.head_b = j
            ob, cb = j, self.m[j]
            q = ob + 1
            while q < cb:
                aattrs, amods, q2 = self.attrs_mods(q)
                if q2 >= cb:
                    break
                acc = Accessor(self.t(q2), q, q, amods)
                q2 += 1
                if self.t(q2) == ';':
                    q2 += 1
                elif self.t(q2) == '=>':
                    e = self.semicolon(q2 + 1, cb)
                    acc.expr = self.simple_stmt(q2 + 1, e, 'expr')
                    q2 = e + 1
                elif self.t(q2) == '{':
                    acc.body = self.parse_block(q2 + 1, self.m[q2])
                    q2 = self.m[q2] + 1
                acc.b = q2
                mem.accessors.append(acc)
                q = q2
            k = cb + 1
            if self.t(k) == '=':   # auto-property initializer
                k = self.semicolon(k, b) + 1
            mem.b = k
            return self.finish(mem), k
        # method-like: ctor dtor method operator indexer
        if self.t(j) != '(':
            e2 = self.semicolon(k, b)
            return None, e2 + 1
        pe = self.m[j]
        mem.params_text = self.text(j + 1, pe)
        mem.params = self.parse_params(j + 1, pe)
        k = pe + 1
        while k < b and self.t(k) not in ('{', '=>', ';'):
            k += 1     # ctor initializer ": base(...)" or "where T : ..."
            if self.t(k - 1) in ('(',):
                k = self.m[k - 1] + 1
        mem.head_b = k
        if self.t(k) == '{':
            mem.body = self.parse_block(k + 1, self.m[k])
            k = self.m[k] + 1
        elif self.t(k) == '=>':
            e = self.semicolon(k + 1, b)
            mem.expr = self.simple_stmt(k + 1, e, 'expr')
            k = e + 1
        else:
            k += 1
        mem.b = k
        return self.finish(mem), k

    def finish(self, mem):
        mem.line = self.line(mem.a)
        mem.end_line = self.line(mem.b - 1)
        return mem

    def parse_params(self, a, b):
        out = []
        for x, y in self.split_commas(a, b, angle=True):
            _, _, k = self.attrs_mods(x)
            while self.t(k) in ('ref', 'out', 'in', 'params', 'this', 'scoped'):
                k += 1
            e = self.skip_type(k)
            dflt = any(self.t(q) == '=' for q in range(x, y))
            if e is not None and e < y and is_ident(self.t(e)):
                out.append((self.text(k, e), self.t(e), dflt))
            elif k < y:
                out.append(('', self.t(y - 1), dflt))
        return out

    # ---- statements
    def parse_block(self, a, b):
        out, k = [], a
        while k < b:
            s, k2 = self.parse_stmt(k, b)
            if s.kind != 'empty':
                out.append(s)
            k = max(k2, k + 1)
        return out

    def simple_stmt(self, a, e, kind='simple'):
        s = Stmt(kind, a, e + 1, a, e)
        return self.done(s)

    def done(self, s):
        s.line = self.line(s.a)
        s.end_line = self.line(s.b - 1)
        s.text = self.text(s.ha, s.hb)
        return s

    def body_list(self, s):
        return s.kids if s.kind == 'block' else [s]

    def parse_stmt(self, k, b):
        t = self.t(k)
        nt = self.t(k + 1)
        if t == '{':
            e = self.m[k]
            s = Stmt('block', k, e + 1, k, k)
            s.kids = self.parse_block(k + 1, e)
            return self.done(s), e + 1
        if t == ';':
            return Stmt('empty', k, k + 1), k + 1
        if t == 'if' and nt == '(':
            ce = self.m[k + 1]
            then, j = self.parse_stmt(ce + 1, b)
            s = Stmt('if', k, j, k + 2, ce)
            s.then = self.body_list(then)
            if self.t(j) == 'else':
                els, j = self.parse_stmt(j + 1, b)
                s.els = self.body_list(els)
            s.b = j
            return self.done(s), j
        if t in ('for', 'foreach', 'while', 'lock', 'fixed', 'using') and nt == '(':
            ce = self.m[k + 1]
            body, j = self.parse_stmt(ce + 1, b)
            s = Stmt(t, k, j, k, ce + 1)
            s.kids = self.body_list(body)
            return self.done(s), j
        if t == 'do':
            body, j = self.parse_stmt(k + 1, b)
            s = Stmt('do', k, j, j, j)
            s.kids = self.body_list(body)
            if self.t(j) == 'while' and self.t(j + 1) == '(':
                ce = self.m[j + 1]
                s.ha, s.hb = j + 2, ce
                j = ce + 1
                if self.t(j) == ';':
                    j += 1
            s.b = j
            return self.done(s), j
        if t == 'switch' and nt == '(' and self.t(self.m[k + 1] + 1) == '{':
            return self.parse_switch(k)
        if t == 'try' and nt == '{':
            return self.parse_try(k)
        if t in ('checked', 'unchecked', 'unsafe') and nt == '{':
            e = self.m[k + 1]
            s = Stmt(t, k, e + 1, k, k + 1)
            s.kids = self.parse_block(k + 2, e)
            return self.done(s), e + 1
        if t in ('return', 'throw', 'break', 'continue', 'goto'):
            e = self.semicolon(k, b)
            return self.done(Stmt(t, k, e + 1, k, e)), e + 1
        if t == 'yield' and nt in ('return', 'break'):
            e = self.semicolon(k, b)
            return self.done(Stmt('yield' if nt == 'return' else 'yieldbreak', k, e + 1, k, e)), e + 1
        if is_ident(t) and nt == ':' and t != 'default':
            body, j = self.parse_stmt(k + 2, b)
            s = Stmt('label', k, j, k, k + 1)
            s.kids = [body]
            return self.done(s), j
        lf = self.local_function(k, b)
        if lf:
            return lf
        e = self.semicolon(k, b)
        return self.simple_stmt(k, e), e + 1

    def local_function(self, k, b):
        j = k
        while self.t(j) in ('static', 'async', 'unsafe', 'extern'):
            j += 1
        e = self.skip_type(j)
        if e is None or not is_ident(self.t(e)) or self.t(j) in KEYWORDS:
            return None
        n = e + 1
        if self.t(n) == '<':
            n = self.skip_angle(n)
            if n is None:
                return None
        if self.t(n) != '(':
            return None
        pe = self.m[n]
        q = pe + 1
        while q < b and self.t(q) == 'where':
            while q < b and self.t(q) not in ('{', '=>'):
                q += 1
        if self.t(q) not in ('{', '=>'):
            return None
        mem = Member('method', self.t(e), self.text(j, e), k, k, None, [self.t(x) for x in range(k, j)])
        mem.params_text = self.text(n + 1, pe)
        mem.params = self.parse_params(n + 1, pe)
        mem.head_b = q
        if self.t(q) == '{':
            mem.body = self.parse_block(q + 1, self.m[q])
            end = self.m[q] + 1
        else:
            se = self.semicolon(q + 1, b)
            mem.expr = self.simple_stmt(q + 1, se, 'expr')
            end = se + 1
        mem.b = end
        self.finish(mem)
        s = Stmt('localfunc', k, end, k, q)
        s.local = mem
        return self.done(s), end

    def parse_switch(self, k):
        ce = self.m[k + 1]
        ob = ce + 1
        cb = self.m[ob]
        s = Stmt('switch', k, cb + 1, k, ce + 1)
        s.sections = []
        cur = None
        j = ob + 1
        while j < cb:
            t = self.t(j)
            if t == 'case' or (t == 'default' and self.t(j + 1) == ':'):
                q = j + 1
                while q < cb and self.t(q) != ':':
                    if self.t(q) in ('(', '[', '{'):
                        q = self.m[q]
                    q += 1
                if cur is None or cur[1]:
                    cur = ([], [])
                    s.sections.append(cur)
                cur[0].append(self.text(j, q))
                j = q + 1
                continue
            st, j2 = self.parse_stmt(j, cb)
            if cur is None:
                cur = (['?'], [])
                s.sections.append(cur)
            if st.kind != 'empty':
                cur[1].append(st)
            j = max(j2, j + 1)
        return self.done(s), cb + 1

    def parse_try(self, k):
        e = self.m[k + 1]
        s = Stmt('try', k, e + 1, k, k + 1)
        s.kids = self.parse_block(k + 2, e)
        s.catches = []
        j = e + 1
        while self.t(j) == 'catch':
            h = j + 1
            if self.t(h) == '(':
                h = self.m[h] + 1
            if self.t(h) == 'when' and self.t(h + 1) == '(':
                h = self.m[h + 1] + 1
            header = self.text(j, h)
            if self.t(h) != '{':
                break
            s.catches.append((header, self.parse_block(h + 1, self.m[h])))
            j = self.m[h] + 1
        if self.t(j) == 'finally' and self.t(j + 1) == '{':
            s.fin = self.parse_block(j + 2, self.m[j + 1])
            j = self.m[j + 1] + 1
        s.b = j
        return self.done(s), j

    # ---- coverage: which source lines ended up in some node
    def cover(self, a, b):
        cov = self.f.covered
        for k in range(max(a, 0), min(b, self.n)):
            tk = self.toks[k]
            cov.update(range(tk.line, tk.end_line + 1))


def walk_stmts(stmts, into_local=True):
    """Every statement, depth first, in source order."""
    for s in stmts or []:
        yield s
        for sub in (s.kids, s.then, s.els, s.fin):
            if sub:
                yield from walk_stmts(sub, into_local)
        for _, body in (s.sections or []):
            yield from walk_stmts(body, into_local)
        for _, body in (s.catches or []):
            yield from walk_stmts(body, into_local)
        if s.local and into_local:
            yield from walk_stmts(s.local.body, into_local)
            if s.local.expr:
                yield s.local.expr


def member_stmts(mem):
    out = list(walk_stmts(mem.body))
    if mem.expr:
        out.append(mem.expr)
    for acc in mem.accessors:
        out.extend(walk_stmts(acc.body))
        if acc.expr:
            out.append(acc.expr)
    return out


# =============================================================== comments

def attach_comments(f: CsFile):
    """Give every comment to the innermost statement, member or type it belongs to."""
    p = f.parser
    anchors = []   # (a, b, depth, obj)

    def add_stmts(stmts, depth):
        for s in stmts or []:
            if s.kind not in ('block', 'empty'):
                anchors.append((s.a, s.b, depth, s))
            for sub in (s.kids, s.then, s.els, s.fin):
                add_stmts(sub, depth + 1)
            for _, body in (s.sections or []):
                add_stmts(body, depth + 1)
            for _, body in (s.catches or []):
                add_stmts(body, depth + 1)
            if s.local:
                anchors.append((s.local.a, s.local.b, depth + 1, s.local))
                add_stmts(s.local.body, depth + 2)

    for td in f.all_types:
        depth = 0
        o = td.outer
        while o:
            depth += 100
            o = o.outer
        anchors.append((td.a, td.b, depth, td))
        for mem in td.members:
            anchors.append((mem.a, mem.b, depth + 10, mem))
            add_stmts(mem.body, depth + 11)
            for acc in mem.accessors:
                add_stmts(acc.body, depth + 11)
    starts = {}
    for a, b, d, obj in anchors:
        if a not in starts or starts[a][0] < d:
            starts[a] = (d, obj)
    tok_starts = [t.start for t in p.toks]
    for c in f.comments:
        if c.pp:
            continue
        nxt = bisect.bisect_left(tok_starts, c.start)   # first token after the comment
        prv = nxt - 1
        obj = None
        if c.own_line and nxt < p.n and nxt in starts:
            obj = starts[nxt][1]
            target = 'lead'
        else:
            k = prv if not c.own_line else nxt
            target = 'trail'
            best = -1
            for a, b, d, o in anchors:
                if a <= k < b and d > best:
                    best, obj = d, o
            if c.own_line and isinstance(obj, (Member, TypeDecl)) and not isinstance(obj, Stmt):
                obj = None   # a loose comment line inside a class or before a closing brace
        if obj is not None and c.text:
            getattr(obj, target).append(c.text)
            c.used = True


