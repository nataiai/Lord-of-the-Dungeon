def stmt_sig(s):
    return s.kind + ':' + s.text


def merge_stmts(old, new, marks, old_text):
    """Old and new statement lists in one tree: unchanged, added, removed (kept in place) and changed."""
    out = []
    sm = difflib.SequenceMatcher(None, [stmt_sig(x) for x in old], [stmt_sig(x) for x in new], autojunk=False)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == 'equal':
            for o, n in zip(old[i1:i2], new[j1:j2]):
                out.append(merge_children(o, n, marks, old_text))
            continue
        olds, news = old[i1:i2], new[j1:j2]
        k = 0
        while k < len(olds) or k < len(news):
            o = olds[k] if k < len(olds) else None
            n = news[k] if k < len(news) else None
            if o is not None and n is not None and o.kind == n.kind:
                merged = merge_children(o, n, marks, old_text)
                marks[merged] = 'changed'
                old_text[merged] = o.text
                out.append(merged)
            else:
                if o is not None:
                    mark_all([o], 'removed', marks)
                    out.append(o)
                if n is not None:
                    mark_all([n], 'added', marks)
                    out.append(n)
            k += 1
    return out


def merge_children(o, n, marks, old_text):
    for name in ('kids', 'then', 'els', 'fin'):
        a, b = getattr(o, name), getattr(n, name)
        if a is not None or b is not None:
            setattr(n, name, merge_stmts(a or [], b or [], marks, old_text))
    if n.sections is not None or o.sections is not None:
        olds = {tuple(lab): body for lab, body in (o.sections or [])}
        merged, used = [], set()
        for lab, body in n.sections or []:
            key = tuple(lab)
            if key in olds:
                used.add(key)
                merged.append((lab, merge_stmts(olds[key], body, marks, old_text)))
            else:
                mark_all(body, 'added', marks)
                merged.append((lab, body))
        for lab, body in o.sections or []:
            if tuple(lab) not in used:
                mark_all(body, 'removed', marks)
                merged.append((lab, body))
        n.sections = merged
    if n.catches is not None or o.catches is not None:
        olds = dict(o.catches or [])
        merged = []
        for h, body in n.catches or []:
            merged.append((h, merge_stmts(olds.get(h, []), body, marks, old_text)))
        for h, body in o.catches or []:
            if h not in dict(n.catches or []):
                mark_all(body, 'removed', marks)
                merged.append((h, body))
        n.catches = merged
    return n


def unit_body(u):
    return u.body if u.body is not None else ([u.expr] if u.expr else [])


def diff_flow(ou, nu):
    """One flowchart for a changed method: the new code, with what was added, removed and changed in color."""
    top = {}
    old = copy_stmts(unit_body(ou), ou, top)
    new = copy_stmts(unit_body(nu), nu, top)
    marks, old_text = {}, {}
    merged = merge_stmts(old, new, marks, old_text)
    f = Flow(nu, marks, top)
    f.body = merged
    f.old_text = old_text
    if ou.head != nu.head:
        marks[nu] = 'changed'
    counts = {}
    for st in walk_stmts(merged, into_local=False):
        if st in marks:
            counts[marks[st]] = counts.get(marks[st], 0) + 1
    return f.build(), counts


def whole_flow(u, mark):
    marks = {u: mark}
    mark_all(unit_body(u), mark, marks)
    return Flow(u, marks).build()


def chart_text(u):
    return Flow(u).build() if not u.trivial else '\n'.join(unit_lines(u))


def diff_page(cfg, oldp, newp, a_label, b_label, notes, out_rel, tool_rel):
    site = Site(cfg, newp, notes, tool_rel)
    ou = {unit_mid(u): u for u in oldp.units if not u.file.external}
    nu = {unit_mid(u): u for u in newp.units if not u.file.external}
    ot = {td.full: td for td in oldp.types if not td.file.external}
    nt = {td.full: td for td in newp.types if not td.file.external}
    ustat = {}
    for k in sorted(set(ou) | set(nu)):
        o, n = ou.get(k), nu.get(k)
        if o is None:
            ustat[k] = 'added'
        elif n is None:
            ustat[k] = 'removed'
        elif o.fp != n.fp or o.head != n.head or chart_text(o) != chart_text(n):
            ustat[k] = 'changed'
    tstat = {}
    for name in sorted(set(ot) | set(nt)):
        o, n = ot.get(name), nt.get(name)
        if o is None:
            tstat[name] = 'added'
        elif n is None:
            tstat[name] = 'removed'
        elif type_fp(o) != type_fp(n) or field_lines(oldp, o) != field_lines(newp, n) or any(
                (u.owner.full == name) for k, u in list(nu.items()) + list(ou.items()) if k in ustat):
            tstat[name] = 'changed'
    files = []
    for name, st in tstat.items():
        td = nt.get(name) or ot.get(name)
        if td.file.path not in files:
            files.append(td.file.path)
    files.sort()

    def count(d, v):
        return sum(1 for x in d.values() if x == v)
    out = ['# Graph diff: `%s` → `%s`' % (a_label, b_label), '']
    if not tstat:
        out += ['No C# changes (comments and spacing count as changes too).', '']
        return '\n'.join(out) + '\n'
    out += ['%d file%s · classes: %d added, %d removed, %d changed · methods: %d added, %d removed, %d changed' % (
        len(files), '' if len(files) == 1 else 's', count(tstat, 'added'), count(tstat, 'removed'),
        count(tstat, 'changed'), count(ustat, 'added'), count(ustat, 'removed'), count(ustat, 'changed')), '',
        'Green: added. Red: removed. Yellow: changed (a changed line also shows what it was). '
        'Arrows in color are calls that appeared or went away.', '',
        '| File | What changed |', '|---|---|']
    sign = {'added': '+', 'removed': '−', 'changed': '~'}
    for path in files:
        items = []
        for k, st in ustat.items():
            u = nu.get(k) or ou.get(k)
            if u.file.path == path:
                items.append('%s `%s`' % (sign[st], u.key))
        for name, st in tstat.items():
            td = nt.get(name) or ot.get(name)
            if td.file.path == path and st != 'changed':
                items.append('%s %s `%s`' % (sign[st], td.kind, name))
        out.append('| [%s](#%s) | %s |' % (path, slug(path), ', '.join(items) or 'fields or comments'))
    out.append('')
    od, _ = overview_data(oldp, {})
    nd, _ = overview_data(newp, {})
    data, nm, em = merge(od, nd)
    for name, st in tstat.items():
        nm.setdefault('t_' + sid(name), st)
    keep = {n.id for n in data.nodes if n.id in nm} | {x for e in data.edges if e in em for x in e[:2]}
    data.nodes = [n for n in data.nodes if n.id in keep]
    data.edges = [e for e in data.edges if e[0] in keep and e[1] in keep]
    if data.nodes:
        out += ['## Changed classes and calls', ''] + site.mermaid(render(data, nm, em))
    for path in files:
        out += ['## ' + path, '']
        for name, st in tstat.items():
            o, n = ot.get(name), nt.get(name)
            td = n or o
            if td.file.path != path:
                continue
            out += ['### %s %s (%s)' % (td.kind, name, st), '']
            data, nm, em = merge(type_data(oldp, o) if o else None, type_data(newp, n) if n else None)
            for k, ust in ustat.items():
                if ust == 'changed':
                    nm.setdefault(k, 'changed')
            out += site.mermaid(render(data, nm, em))
            for k, ust in ustat.items():
                u = nu.get(k) or ou.get(k)
                if u.owner.full != name:
                    continue
                o_u, n_u = ou.get(k), nu.get(k)
                charted = (n_u is not None and not n_u.trivial) or (o_u is not None and not o_u.trivial)
                if not charted:
                    continue
                if ust == 'changed':
                    code, counts = diff_flow(o_u, n_u)
                    detail = ', '.join('%d %s' % (v, k2) for k2, v in sorted(counts.items())) or 'comments'
                    out += ['#### %s (changed: %s)' % (u.key, detail), ''] + site.mermaid(code)
                else:
                    out += ['#### %s (%s)' % (u.key, ust), ''] + site.mermaid(whole_flow(u, ust))
    return '\n'.join(out).rstrip() + '\n'


