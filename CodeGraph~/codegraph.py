def cmd_diff(cfg, base, head, out_dir):
    old_src = git_sources(cfg, base)
    new_src = git_sources(cfg, head) if head else None
    oldp, newp = load_project(cfg, old_src), load_project(cfg, new_src)
    notes = load_notes(os.path.join(HERE, cfg['notes']))
    out_dir = os.path.abspath(out_dir or os.path.join(HERE, cfg['out']))
    out_rel = os.path.relpath(out_dir, cfg['root_abs']).replace(os.sep, '/')
    md = diff_page(cfg, oldp, newp, base, head or 'working tree', notes, out_rel, tool_rel_path(cfg))
    os.makedirs(out_dir, exist_ok=True)
    for name, text in (('diff.md', md), ('diff.html', html_page('Graph diff', md))):
        with open(os.path.join(out_dir, name), 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
    print(md.split('\n')[2] if md.count('\n') > 2 else md)
    print('Wrote %s and diff.html (open it in a browser).' % os.path.join(out_dir, 'diff.md'))
    return 0


# =============================================================== command line

def main(argv=None):
    ap = argparse.ArgumentParser(prog='codegraph.py', description=__doc__.split('\n\n')[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    sub = ap.add_subparsers(dest='cmd')
    sub.add_parser('generate', help='regenerate graphs/ (the default)')
    sub.add_parser('check', help='exit 1 if graphs/ is out of date')
    sub.add_parser('todo', help='notes to write or update')
    d = sub.add_parser('diff', help='graph diff between two git revisions')
    d.add_argument('base', nargs='?', default='HEAD', help='old revision (default HEAD)')
    d.add_argument('head', nargs='?', default=None, help='new revision (default: the working tree)')
    d.add_argument('-o', '--out', default=None, help='folder for diff.md and diff.html (default CodeGraph~/out)')
    args = ap.parse_args(argv)
    cfg = load_config()
    if args.cmd in (None, 'generate'):
        return cmd_generate(cfg)
    if args.cmd == 'check':
        return cmd_generate(cfg, check=True)
    if args.cmd == 'todo':
        return cmd_todo(cfg)
    if args.cmd == 'diff':
        return cmd_diff(cfg, args.base, args.head, args.out)
    return 2


if __name__ == '__main__':
    sys.exit(main())
