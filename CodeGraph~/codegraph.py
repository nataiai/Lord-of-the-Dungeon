def note_status(site):
    """[(kind, key, file, expected hash, note or None)] for every class and charted method; plus orphans."""
    rows = []
    for f in site.proj.files:
        if f.external:
            continue
        fnote, sections = site.note_for(f)
        rows.append(('file', f.path, f, file_fp(f), fnote if fnote.text else None))
        for td in f.all_types:
            if td.kind != 'enum':
                rows.append(('class', td.full, f, type_fp(td), sections.get(td.full)))
            for u in site.proj.units_of_type.get(td, []):
                if u in site.has_chart:
                    rows.append(('method', u.key, f, u.fp, sections.get(u.key)))
    orphans = []
    known = {f.path: {td.full for td in f.all_types} | {u.key for u in site.proj.units if u.file is f}
             for f in site.proj.files}
    for path, (_, sections) in sorted(site.notes.items()):
        if path == 'README':
            continue
        for key, n in sections.items():
            if key not in known.get(path, set()):
                orphans.append((path, key, n))
    return rows, orphans


