def is_message(proj, u):
    return u.acc is None and u.kind == 'method' and u.member.name in UNITY_MESSAGES and proj.is_engine_type(u.owner)


def unit_title(u):
    """Short name used in boxes outside the unit's own file: Type.Method() or Type.Prop { set }."""
    if u.acc is not None:
        return '%s.%s { %s }' % (u.owner.full, u.member.name, u.acc.kind)
    if '(' in u.key:
        return u.key
    if u.kind == 'local':
        return u.key + '()'
    return '%s.%s()' % (u.owner.full, u.member.name if u.kind != 'ctor' else u.owner.name)


def unit_lines(u):
    lines = [u.head]
    if u.trivial:
        stmts = [u.expr] if u.expr is not None else (u.body or [])
        comments = []
        for s in stmts:
            comments += s.lead + s.trail
        if u.expr is not None:
            lines.append('=> ' + u.expr.text)
        elif u.body is not None:
            lines.append('{ ' + '; '.join(s.text for s in u.body) + ' }' if u.body else '{ }')
        lines += comment_lines(u.lead + u.trail + comments)
    return lines


def type_title(td):
    p = td.file.parser
    head = p.text(td.a, td.head_b)
    return [head] + comment_lines(td.lead + td.trail)


def decl_lines(p, mem, elide=()):
    """Source lines of a declaration with its comments; accessor bodies in elide are shown as {…}."""
    f = p.f
    lines = comment_lines(mem.lead)
    skip = {}
    for a, b, kind in elide:
        skip[a] = (b, kind)
    k, cur_line, parts = mem.a, None, []
    rows = []
    while k < mem.b:
        tk = p.toks[k]
        if k in skip:
            b, kind = skip[k]
            text, k = kind + '{…}', b
        else:
            text, k = tk.text.replace('\n', ' '), k + 1
        if tk.line != cur_line:
            if parts:
                rows.append([cur_line, ''.join(parts)])
            cur_line, parts = tk.line, [text]
        else:
            parts.append((' ' if tk.gap else '') + text)
    if parts:
        rows.append([cur_line, ''.join(parts)])
    start = p.toks[mem.a].start
    end = p.toks[mem.b - 1].end
    nxt = p.toks[mem.b].start if mem.b < p.n else len(f.src)
    by_line = {}
    for c in f.comments:
        if c.pp or not c.text:
            continue
        if start <= c.start < end or (end <= c.start < nxt and not c.own_line):
            by_line.setdefault(c.line, []).append(c)
    out_rows = []
    for ln, text in rows:
        own = [c for c in by_line.get(ln, []) if c.own_line]
        for c in own:
            out_rows.append('// ' + c.text)
        tail = [c.text for c in by_line.get(ln, []) if not c.own_line]
        out_rows.append(text + ('  // ' + ' // '.join(tail) if tail else ''))
    for ln in sorted(by_line):   # own-line comments on lines without code inside the declaration
        if all(ln != r[0] for r in rows):
            out_rows += ['// ' + c.text for c in by_line[ln]]
    return lines + out_rows


def field_lines(proj, td):
    p = td.file.parser
    lines = []
    for mem in td.members:
        if mem.kind in METHOD_KINDS or mem.kind == 'enum':
            continue
        elide = []
        for acc in mem.accessors:
            u = proj.unit_of.get((mem, acc.kind))
            if u is not None and u.shown:
                elide.append((acc.a, acc.b, acc.kind))
        lines += decl_lines(p, mem, elide)
    return lines


def enum_lines(td):
    p = td.file.parser
    items = []
    for mem in td.members:
        items.append(p.text(mem.a, mem.b) + (' // ' + ' // '.join(mem.trail) if mem.trail else ''))
    lines, cur = [], ''
    for it in items:
        if '//' in it:
            if cur:
                lines.append(cur.rstrip(', '))
                cur = ''
            lines.append(it)
        elif len(cur) + len(it) > 60:
            lines.append(cur.rstrip(', '))
            cur = it + ', '
        else:
            cur += it + ', '
    if cur:
        lines.append(cur.rstrip(', '))
    return lines


@dataclass(eq=False)
class GNode:
    id: str
    shape: str
    lines: List[str]
    cls: Optional[str]
    width: int
    group: Optional[str] = None


@dataclass(eq=False)
class GData:
    """A graph as data, so the same code draws it normally and as a diff (two GData merged)."""
    direction: str
    groups: list = field(default_factory=list)     # (id, title lines)
    nodes: list = field(default_factory=list)      # GNode
    edges: list = field(default_factory=list)      # (a, b, label, style)  style: '' dotted thick
    changed: set = field(default_factory=set)      # node ids whose code changed even if their text did not

    def node(self, *a, **k):
        n = GNode(*a, **k)
        self.nodes.append(n)
        return n

    def edge(self, a, b, lab='', style=''):
        e = (a, b, lab, style)
        if e not in self.edges:
            self.edges.append(e)


def render(d, node_marks=None, edge_marks=None):
    node_marks, edge_marks = node_marks or {}, edge_marks or {}
    g = Graph(d.direction)

    def cls(n):
        m = node_marks.get(n.id)
        return (m + 'F' if n.cls == 'fields' else m) if m else n.cls
    for gid, title in d.groups:
        g.open(gid, title)
        for n in d.nodes:
            if n.group == gid:
                g.node(n.id, n.shape, n.lines, cls(n), n.width)
        g.close()
    for n in d.nodes:
        if n.group is None:
            g.node(n.id, n.shape, n.lines, cls(n), n.width)
    for e in d.edges:
        a, b, lab, style = e
        g.edge(a, b, lab, style == 'dotted', cls=edge_marks.get(e))
        if style == 'thick':
            g.thick.add(len(g.edges) - 1)
    return g.render()


def merge(old, new):
    """Old and new graph data in one: returns (data, node marks, edge marks) for added/removed/changed."""
    old = old or GData(new.direction if new else 'LR')
    new = new or GData(old.direction)
    d = GData(new.direction)
    nm, em = {}, {}
    on = {n.id: n for n in old.nodes}
    nn = {n.id: n for n in new.nodes}
    d.groups = list(new.groups) + [g for g in old.groups if g[0] not in {x[0] for x in new.groups}]
    for n in new.nodes:
        o = on.get(n.id)
        if o is None:
            nm[n.id] = 'added'
            d.nodes.append(n)
        elif o.lines != n.lines or n.id in new.changed or n.id in old.changed:
            nm[n.id] = 'changed'
            if n.cls == 'fields' and o.lines != n.lines:
                n = GNode(n.id, n.shape, line_diff(o.lines, n.lines), n.cls, n.width, n.group)
            d.nodes.append(n)
        else:
            d.nodes.append(n)
    for n in old.nodes:
        if n.id not in nn:
            nm[n.id] = 'removed'
            d.nodes.append(n)
    for e in new.edges:
        d.edges.append(e)
        if e not in old.edges:
            em[e] = 'added'
    for e in old.edges:
        if e not in new.edges:
            d.edges.append(e)
            em[e] = 'removed'
    return d, nm, em


def line_diff(a, b):
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == 'equal':
            out += a[i1:i2]
        else:
            out += ['- ' + x for x in a[i1:i2]] + ['+ ' + x for x in b[j1:j2]]
    return out


def unit_mid(u):
    """Id of a method box that stays the same across versions (also when an overload is added)."""
    sig = ','.join(base_type_name(t) for t, _, _ in u.member.params) if u.acc is None else u.acc.kind
    return 'u_' + sid(u.owner.full + '__' + (u.member.name if u.kind != 'local' else u.key) + '__' + sig)


def type_data(proj, td):
    """One class: its fields, its methods, who calls them (from anywhere) and what they call, and Unity's calls."""
    d = GData('LR')
    if td.kind == 'enum':
        d.node('t_' + sid(td.full), 'block', ['enum ' + td.name] + enum_lines(td) + comment_lines(td.lead + td.trail),
               'fields', 70)
        return d
    if td.kind == 'delegate':
        d.node('t_' + sid(td.full), 'block', [proj.type_head(td)] + comment_lines(td.lead + td.trail), 'fields', 70)
        return d
    mine = [u for u in proj.units_of_type.get(td, []) if u.shown]
    mine_set = set(mine)
    gid = 't_' + sid(td.full)
    d.groups.append((gid, [proj.type_head(td)]))
    fl = comment_lines(td.lead + td.trail) + field_lines(proj, td)
    if fl:
        d.node('f_' + sid(td.full), 'block', fl, 'fields', 76, gid)
    for u in mine:
        shape = 'start' if is_message(proj, u) else ('round' if u.acc is not None else 'block')
        d.node(unit_mid(u), shape, unit_lines(u), 'start' if shape == 'start' else None, 56, gid)
    if not fl and not mine:
        d.node('e_' + sid(td.full), 'block', ['(empty)'], None, 40, gid)
    outside = {}

    def ref(u):
        if u not in mine_set and u not in outside:
            lines = [unit_title(u)]
            if u.overridden_by:
                lines.append('overridden in ' + ', '.join(sorted({x.owner.full for x in u.overridden_by})))
            outside[u] = lines
        return unit_mid(u)
    edges = []
    by_name = ('subscribes', 'unsubscribes', 'by name')
    for u in mine:
        for t, lab in u.calls:
            if t.shown:
                edges.append((unit_mid(u), ref(t), lab, 'dotted' if lab in by_name else ''))
    for u in mine:
        for c, lab in sorted(u.callers, key=lambda x: x[0].key):
            if c.shown and c not in mine_set:
                edges.append((ref(c), unit_mid(u), lab, 'dotted' if lab in by_name else ''))
        for c, lab in sorted(u.vcallers, key=lambda x: x[0].key):
            if c.shown:
                edges.append((ref(c), unit_mid(u), 'virtual', 'dotted'))
    for u, lines in outside.items():
        d.node(unit_mid(u), 'block', lines, 'ext' if u.file.external else 'other', 50)
    msgs = [u for u in mine if is_message(proj, u)]
    if msgs:
        d.node('unity', 'circle', ['Unity'], 'engine', 20)
        for u in msgs:
            d.edge('unity', unit_mid(u), UNITY_MESSAGES[u.member.name])
    for e in edges:
        d.edge(*e)
    return d


