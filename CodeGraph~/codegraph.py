def git(args, cwd):
    r = subprocess.run(['git'] + args, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if r.returncode != 0:
        raise SystemExit('git %s failed: %s' % (' '.join(args), r.stderr.decode('utf-8', 'replace').strip()))
    return r.stdout


def git_sources(cfg, rev):
    root = cfg['root_abs']
    out = {}
    listing = git(['ls-tree', '-r', '-z', '--name-only', rev, '--', '.'], root).decode('utf-8', 'replace')
    for name in listing.split('\0'):
        parts = name.split('/')
        if not name.endswith('.cs') or any(x.startswith('.') or x.endswith('~') for x in parts):
            continue
        if not is_under(name, cfg['ignore']):
            out[name] = git(['show', '%s:./%s' % (rev, name)], root).decode('utf-8', 'replace').lstrip('﻿')
    return out


def copy_stmts(stmts, unit, top):
    """Copy a statement tree (the diff merges old and new statements without touching the parsed code)."""
    out = []
    for s in stmts or []:
        c = Stmt(**{k: getattr(s, k) for k in s.__dataclass_fields__})
        c.lead, c.trail = list(s.lead), list(s.trail)
        for name in ('kids', 'then', 'els', 'fin'):
            sub = getattr(s, name)
            if sub is not None:
                setattr(c, name, copy_stmts(sub, unit, top))
        if s.sections is not None:
            c.sections = [(list(lab), copy_stmts(body, unit, top)) for lab, body in s.sections]
        if s.catches is not None:
            c.catches = [(h, copy_stmts(body, unit, top)) for h, body in s.catches]
        if s in unit.top:
            top[c] = unit.top[s]
        out.append(c)
    return out


