def write_pages(out_dir, pages, check=False):
    """Write pages that changed; remove generated pages whose source is gone. Returns the changed paths."""
    changed = []
    existing = set()
    if os.path.isdir(out_dir):
        for dirpath, _, filenames in os.walk(out_dir):
            for fn in filenames:
                path = os.path.join(dirpath, fn)
                rel = os.path.relpath(path, out_dir).replace(os.sep, '/')
                if fn.endswith('.md') and read_text(path).startswith(GENERATED_MARK):
                    existing.add(rel)
    for rel, content in sorted(pages.items()):
        path = os.path.join(out_dir, rel)
        old = read_text(path) if os.path.exists(path) else None
        if old != content:
            changed.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, 'w', encoding='utf-8', newline='\n') as fh:
                    fh.write(content)
    for rel in sorted(existing - set(pages)):
        changed.append(rel + ' (removed)')
        if not check:
            os.remove(os.path.join(out_dir, rel))
            d = os.path.dirname(os.path.join(out_dir, rel))
            while d != out_dir and os.path.isdir(d) and not os.listdir(d):
                os.rmdir(d)
                d = os.path.dirname(d)
    return changed


